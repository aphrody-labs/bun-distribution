/** Name of the canonical example project. */
export const EXAMPLE_NAME = "aphrody-example";

/** The single example: a Tauri 3 desktop app on the M3 packages. Everything else is generated from it. */
export function exampleFiles(name = EXAMPLE_NAME): FileMap {
  return {
    ...appFiles({ name, target: "tauri", modernizeM3: true }),
    "README.md": `<!-- SPDX-License-Identifier: Apache-2.0 -->

# ${name}

The canonical Aphrody UI example, generated by \`aphrody-scaffold example\`: a Bun + React app on the
M3 packages, wrapped in a Tauri 3 shell (explicit wry runtime, opener plugin).

\`\`\`sh
bun install
bun run dev        # web preview on http://localhost:1420
Native Tauri activation requires a registered canonical Rust shell and its Workspace factory.
\`\`\`
`,
  };
}

export type TemplateName = "web" | "app" | "example";

export interface TemplateInfo {
  name: TemplateName;
  summary: string;
}

export const TEMPLATES: readonly TemplateInfo[] = [
  { name: "web", summary: "Bun + M3 web project (m3 new)" },
  {
    name: "app",
    summary: "Bun + React app with the Next.js shims, desktop (Tauri 3) or web",
  },
  { name: "example", summary: "the canonical example: app + Tauri 3 + M3" },
];

export type ScaffoldRequest =
  | ({ template: "web" } & WebTemplateOptions)
  | ({ template: "app" } & AppTemplateOptions)
  | { template: "example"; name?: string };

/** Files of a template, without writing anything. */
export function renderTemplate(request: ScaffoldRequest): FileMap {
  switch (request.template) {
    case "web":
      return webFiles(request);
    case "app":
      return appFiles(request);
    case "example":
      return exampleFiles(request.name);
  }
}

/** Renders a template and writes it. Returns the paths written. */
export async function scaffold(
  outDir: string,
  request: ScaffoldRequest,
  mode: WriteMode = "empty",
): Promise<string[]> {
  assertPrivateOwnerWorkspace(outDir);
  if (request.template !== "web")
    assertNativeShellOwner(
      request.template === "example" ? "tauri" : (request.target ?? "tauri"),
    );
  return writeFiles(outDir, renderTemplate(request), mode);
}
