/**
 * The Tauri 3 shell of every generated project: `src-tauri/` with the pinned crates, an explicit
 * runtime, a capability file and an icon. One generator for the migrated app, the wrapped site and
 * the canonical example, so the pins and the lean feature set live in one place.
 */
import type { FileMap } from "./files.ts";
import { crateName } from "./names.ts";
import { solidIconPng } from "./png.ts";
import { TAURI_3, TAURI_CEF, tauriSchemaUrl } from "./pins.ts";

export type TauriEngine = "wry" | "cef";

export interface TauriShellOptions {
  /** `productName`. */
  name: string;
  identifier: string;
  version?: string;
  /** Cargo package name; derived from `name` by default. */
  crate?: string;
  engine?: TauriEngine;
  /** Adds the library entry point required by Tauri Android/iOS hosts (wry only). */
  mobile?: boolean;
  build: {
    frontendDist: string;
    devUrl?: string;
    beforeDevCommand?: string;
    beforeBuildCommand?: string;
  };
  /** `config`: one window in `tauri.conf.json`. `runtime`: none; a plugin creates it. */
  window?:
    | {
        mode: "config";
        title: string;
        width: number;
        height: number;
        resizable?: boolean;
      }
    | { mode: "runtime" };
  /** Exposes `window.__TAURI__` to the page (migrated apps use it through shims). */
  withGlobalTauri?: boolean;
  /** `null` disables the CSP injected into local assets. */
  csp?: string | null;
  /** `tauri-plugin-opener` and its permission. */
  openerPlugin?: boolean;
  /** `serde` and `serde_json` for the commands the app adds later. */
  serde?: boolean;
  /**
   * A runtime plugin crate (`aphrody-tauri-wrap`): `init` is the Rust expression that builds it.
   * `features` selects its Cargo features: absent, the crate's defaults (`bundle`: the loopback
   * server of the bundle mode); an array, `default-features = false` plus those features, so a
   * remote or sidecar app does not compile the HTTP stack of the bundle server.
   */
  runtimePlugin?: {
    crate: string;
    path: string;
    init: string;
    features?: string[];
  };
  /**
   * Optional `debug-bridge` feature (wry only) for parity checks, hosted by `aphrody-tauri-wrap`
   * (`aphrody_tauri_wrap::debug`). `true` reuses the `aphrody-tauri-wrap` runtime plugin; `{ path }`
   * (the wrap crate directory) is for a shell that has no such runtime plugin and adds the crate as
   * an optional dependency without its default features.
   */
  debugBridge?: boolean | { path: string };
  externalBin?: string[];
  permissions?: string[];
  capabilityDescription?: string;
  /** Adds `$schema` to the capability file (the schema is generated by the first `tauri build`). */
  capabilitySchema?: boolean;
  /** RGBA PNG, at least 256 px. A solid placeholder when absent. */
  icon?: Uint8Array;
}

function posix(path: string): string {
  return path.replaceAll("\\", "/");
}

/** Crate that hosts the debug bridge (`aphrody_tauri_wrap::debug`); it was `aphrody-tauri-debug`. */
const DEBUG_HOST_CRATE = "aphrody-tauri-wrap";

function features(list: readonly string[]): string {
  return `[${list.map((feature) => `"${feature}"`).join(", ")}]`;
}

/** The runtime plugin's dependency line: crate defaults unless `features` is set. */
function runtimePluginLine(
  plugin: NonNullable<TauriShellOptions["runtimePlugin"]>,
): string {
  const parts = [`path = "${posix(plugin.path)}"`];
  if (plugin.features) {
    parts.push("default-features = false");
    if (plugin.features.length > 0)
      parts.push(`features = ${features(plugin.features)}`);
  }
  return `${plugin.crate} = { ${parts.join(", ")} }`;
}

/**
 * How the app depends on the debug bridge: through the wrap runtime plugin it already has (the
 * feature only forwards), or through an optional dependency on the wrap crate.
 */
function debugBridgeMode(
  options: TauriShellOptions,
): { kind: "runtime" } | { kind: "optional"; path: string } | null {
  if ((options.engine ?? "wry") !== "wry" || !options.debugBridge) return null;
  if (options.runtimePlugin?.crate === DEBUG_HOST_CRATE)
    return { kind: "runtime" };
  if (typeof options.debugBridge === "object") {
    return { kind: "optional", path: options.debugBridge.path };
  }
  throw new Error(
    `debugBridge: true needs the ${DEBUG_HOST_CRATE} runtime plugin; pass { path } to the crate instead`,
  );
}

export function tauriConf(options: TauriShellOptions): Record<string, unknown> {
  const window = options.window ?? { mode: "runtime" };
  const build: Record<string, string> = {};
  if (options.build.beforeDevCommand)
    build.beforeDevCommand = options.build.beforeDevCommand;
  if (options.build.devUrl) build.devUrl = options.build.devUrl;
  if (options.build.beforeBuildCommand)
    build.beforeBuildCommand = options.build.beforeBuildCommand;
  build.frontendDist = options.build.frontendDist;
  return {
    $schema: tauriSchemaUrl(),
    productName: options.name,
    version: options.version ?? "0.1.0",
    identifier: options.identifier,
    build,
    app: {
      ...(options.withGlobalTauri ? { withGlobalTauri: true } : {}),
      windows:
        window.mode === "config"
          ? [
              {
                title: window.title,
                width: window.width,
                height: window.height,
                resizable: window.resizable ?? true,
              },
            ]
          : [],
      security: { csp: options.csp ?? null },
    },
    bundle: {
      active: true,
      targets: "all",
      icon: ["icons/icon.png"],
      ...(options.externalBin ? { externalBin: options.externalBin } : {}),
    },
    plugins: {},
  };
}

export function cargoToml(options: TauriShellOptions): string {
  const engine = options.engine ?? "wry";
  const runtime =
    engine === "cef"
      ? `tauri-runtime-cef = { version = "=${TAURI_CEF}", features = ["macos-private-api"] }`
      : `tauri-runtime-wry = { version = "=${TAURI_3.runtimeWry}", default-features = false, features = ["x11"] }`;
  const debug = debugBridgeMode(options);
  const lines = [
    "# SPDX-License-Identifier: Apache-2.0",
    "[package]",
    `name = "${options.crate ?? crateName(options.name)}"`,
    `version = "${options.version ?? "0.1.0"}"`,
    'edition = "2021"',
    "publish = false",
    "",
    "# Standalone workspace: the project never joins a parent Cargo workspace.",
    "[workspace]",
    "",
  ];
  if (options.mobile) {
    if (engine !== "wry") throw new Error("Tauri mobile requires the wry host");
    lines.push(
      "[lib]",
      `name = "${(options.crate ?? crateName(options.name)).replaceAll("-", "_")}_lib"`,
      'crate-type = ["staticlib", "cdylib", "rlib"]',
      "",
    );
  }
  lines.push("[features]", 'custom-protocol = ["tauri/custom-protocol"]');
  if (debug) {
    lines.push(
      "# Debug bridge used by the parity check (wry only): APHRODY_TAURI_DEBUG=1 cargo run --features debug-bridge",
      debug.kind === "runtime"
        ? `debug-bridge = ["${DEBUG_HOST_CRATE}/debug-bridge"]`
        : `debug-bridge = ["dep:${DEBUG_HOST_CRATE}", "${DEBUG_HOST_CRATE}/debug-bridge"]`,
    );
  }
  lines.push(
    "",
    "[build-dependencies]",
    `tauri-build = "=${TAURI_3.build}"`,
    "",
    "[dependencies]",
    `tauri = { version = "=${TAURI_3.tauri}", default-features = false, features = ["compression"] }`,
    runtime,
  );
  if (options.openerPlugin)
    lines.push(`tauri-plugin-opener = "=${TAURI_3.pluginOpener}"`);
  if (options.runtimePlugin)
    lines.push(runtimePluginLine(options.runtimePlugin));
  if (debug?.kind === "optional")
    lines.push(
      `${DEBUG_HOST_CRATE} = { path = "${posix(debug.path)}", default-features = false, optional = true }`,
    );
  if (options.serde)
    lines.push(
      'serde = { version = "1.0", features = ["derive"] }',
      'serde_json = "1.0"',
    );
  lines.push(
    "",
    "[profile.release]",
    "codegen-units = 1",
    "lto = true",
    'opt-level = "s"',
    'panic = "abort"',
    "strip = true",
    "",
  );
  return lines.join("\n");
}

export function mainRs(options: TauriShellOptions): string {
  if (options.mobile) {
    const library = `${(options.crate ?? crateName(options.name)).replaceAll("-", "_")}_lib`;
    return `// SPDX-License-Identifier: Apache-2.0
#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]
fn main() {
    ${library}::run();
}
`;
  }
  const engine = options.engine ?? "wry";
  const plugins = [
    ...(options.openerPlugin ? ["tauri_plugin_opener::init()"] : []),
    ...(options.runtimePlugin ? [options.runtimePlugin.init] : []),
  ];
  const pluginLines = plugins
    .map((plugin) => `        .plugin(${plugin})\n`)
    .join("");
  const chain = [
    "tauri::Builder::default()",
    ".runtime(Wry::default())",
    ...plugins.map((plugin) => `.plugin(${plugin})`),
  ].join("\n        ");
  const header =
    '// Prevents additional console window on Windows in release\n#![cfg_attr(not(debug_assertions), windows_subsystem = "windows")]\n';
  if (engine === "cef") {
    return `${header}
use tauri_runtime_cef::{Cef, CefRuntime};

#[tauri_runtime_cef::cef_entry_point]
fn main() {
    let cef = Cef::default();
    // Debug builds only: APHRODY_WRAP_CDP_PORT=9333 exposes Chromium's DevTools protocol on loopback
    // for the parity check.
    #[cfg(debug_assertions)]
    let cef = match std::env::var("APHRODY_WRAP_CDP_PORT").ok().and_then(|value| value.parse::<u16>().ok()) {
        Some(port) => cef.remote_debugging(tauri_runtime_cef::RemoteDebugging::Port {
            port,
            allowed_origins: Vec::new(),
        }),
        None => cef,
    };
    tauri::Builder::<CefRuntime>::new()
        .runtime(cef)
${pluginLines}        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}
`;
  }
  const bridge = debugBridgeMode(options)
    ? `    #[cfg(feature = "debug-bridge")]
    let builder = builder.plugin(aphrody_tauri_wrap::debug::init());
`
    : "";
  return `${header}
use tauri_runtime_wry::Wry;

fn main() {
    let builder = ${chain};
${bridge}    builder
        .run(tauri::generate_context!())
        .expect("error while running tauri application");
}
`;
}

export function capability(
  options: TauriShellOptions,
): Record<string, unknown> {
  const permissions = options.permissions ?? [
    "core:default",
    ...(options.openerPlugin ? ["opener:default"] : []),
  ];
  return {
    ...(options.capabilitySchema
      ? { $schema: "../gen/schemas/desktop-schema.json" }
      : {}),
    identifier: "default",
    description:
      options.capabilityDescription ??
      "Default capabilities for the desktop app",
    windows: ["main"],
    permissions,
  };
}

/** Mobile and desktop share one lifecycle entry point; binaries call this library. */
export function libRs(options: TauriShellOptions): string {
  if ((options.engine ?? "wry") !== "wry")
    throw new Error("Tauri mobile requires the wry host");
  return mainRs({ ...options, mobile: false })
    .replace(
      /\/\/ Prevents additional console window on Windows in release\n#!\[cfg_attr\(not\(debug_assertions\), windows_subsystem = "windows"\)\]\n/,
      "// SPDX-License-Identifier: Apache-2.0\n",
    )
    .replace(
      "fn main()",
      "#[cfg_attr(mobile, tauri::mobile_entry_point)]\npub fn run()",
    );
}

/** `src-tauri/**` files of the shell. Paths are relative to the project root. */
export function tauriShell(options: TauriShellOptions): FileMap {
  return {
    "src-tauri/tauri.conf.json": `${JSON.stringify(tauriConf(options), null, 2)}\n`,
    "src-tauri/Cargo.toml": cargoToml(options),
    "src-tauri/build.rs": "fn main() {\n    tauri_build::build()\n}\n",
    "src-tauri/src/main.rs": mainRs(options),
    ...(options.mobile ? { "src-tauri/src/lib.rs": libRs(options) } : {}),
    "src-tauri/capabilities/default.json": `${JSON.stringify(capability(options), null, 2)}\n`,
    "src-tauri/icons/icon.png": options.icon ?? solidIconPng(),
  };
}
