// Small helpers shared by the m3-bun modules.
import { lstat, mkdir } from "node:fs/promises";
import { homedir } from "node:os";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";

/** The yolo checkout: `$YOLO_ROOT`, else `~/yolo`. Host conventions and the runtime SDK are resolved under it. */
export function yoloRoot(): string {
  return resolve(Bun.env.YOLO_ROOT ?? join(homedir(), "yolo"));
}

/** `@scope/name` -> `name`; anything not a valid DNS-ish label becomes `-`. */
export function slug(name: string): string {
  return (
    name
      .replace(/^@[^/]+\//, "")
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, "-")
      .replace(/^-+|-+$/g, "") || "app"
  );
}

export interface GeneratedFile {
  /** Path relative to the target's output directory, `/`-separated. */
  path: string;
  content: string;
  /** Unix mode (default 0o644). */
  mode?: number;
}

/** Write generated files below `dir`; returns the absolute paths written. Never touches anything else. */
export async function writeFiles(
  dir: string,
  files: ReadonlyArray<
    Omit<GeneratedFile, "content"> & { content: string | Uint8Array }
  >,
): Promise<string[]> {
  const written: string[] = [];
  /* eslint-disable no-await-in-loop -- Files and ancestor checks are ordered to preserve containment and repeated-path writes. */
  for (const file of files) {
    const target = resolve(dir, file.path);
    const inside = relative(resolve(dir), target);
    if (
      inside === "" ||
      inside === ".." ||
      inside.startsWith(`..${sep}`) ||
      isAbsolute(inside)
    )
      throw new Error(
        `m3-bun: generated path escapes its directory: ${file.path}`,
      );
    let ancestor = resolve(dir);
    for (const part of inside.split(sep)) {
      ancestor = join(ancestor, part);
      try {
        if ((await lstat(ancestor)).isSymbolicLink())
          throw new Error(
            `m3-bun: generated path contains a symlink: ${file.path}`,
          );
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== "ENOENT") throw error;
      }
    }
    await mkdir(dirname(target), { recursive: true });
    await Bun.write(target, file.content);
    if (file.mode !== undefined && process.platform !== "win32")
      await Bun.$`chmod ${file.mode.toString(8)} ${target}`.quiet();
    written.push(target);
  }
  /* eslint-enable no-await-in-loop */
  return written;
}

/** Hex SHA-256 of bytes or text. */
export function sha256(data: string | Uint8Array): string {
  return new Bun.CryptoHasher("sha256").update(data).digest("hex");
}

/** Format a byte count as KiB with one decimal. */
export const kib = (bytes: number): string =>
  `${(bytes / 1024).toFixed(1)} KiB`;

/** Shell-quote one argument for generated scripts. */
export function shq(value: string): string {
  return /^[A-Za-z0-9_./:=@%+-]+$/.test(value)
    ? value
    : `'${value.replaceAll("'", "'\\''")}'`;
}

