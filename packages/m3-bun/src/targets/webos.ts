// Desktop window over `Bun.WebView`, the pattern of the Bun fork desktop (apps/desktop/desktop):
// the compiled executable serves the app on a free loopback port and a Chrome-backed `Bun.WebView` window
// (`headless: false`) shows it; closing the window stops the server. `--smoke` instead opens the page headless
// through `@aphrody/bun-webview-page` (`verifyWebView`) and prints a JSON report. The WebOS shell itself cannot
// list an external app: its apps are a closed TypeScript union, so this target ships the window, not a WebOS entry.
import type { Target, TargetContext, TargetFile } from "@aphrody/m3-bun/targets";

const GENERATED_NOTE = "Generated by @aphrody/m3-bun";

export interface WebViewReport {
  url: string;
  /** Browser product reported by Chrome over CDP. */
  browser: string;
  title: string;
  /** HTTP status of the main document. */
  status: number | undefined;
  /** `/healthz` of the same origin answered 200. */
  healthy: boolean;
  /** Console errors and uncaught page exceptions while the page loaded. */
  errors: string[];
  screenshot?: Uint8Array;
  ok: boolean;
}

export interface VerifyWebViewOptions {
  /** Capture a PNG of the viewport. */
  screenshot?: boolean;
  timeout?: number;
  /** Chrome executable (default: what Bun.WebView finds, `BUN_CHROME_PATH` first). */
  executablePath?: string;
  args?: string[];
}

/** Open `url` in a headless Chrome-backed `Bun.WebView` through `@aphrody/bun-webview-page` and report what loaded. */
export async function verifyWebView(url: string, options: VerifyWebViewOptions = {}): Promise<WebViewReport> {
  let page: typeof import("@aphrody/bun-webview-page");
  try {
    page = await import("@aphrody/bun-webview-page");
  } catch (error) {
    throw new Error(`m3-bun: verifyWebView needs @aphrody/bun-webview-page (${(error as Error).message})`, {
      cause: error,
    });
  }
  const browser = await page.chromium.launch({
    ...(options.executablePath ? { executablePath: options.executablePath } : {}),
    ...(options.args ? { args: options.args } : {}),
  });
  try {
    const tab = await browser.newPage();
    const errors: string[] = [];
    let status: number | undefined;
    tab.on("console", message => {
      if (message.type() === "error") errors.push(message.text());
    });
    tab.on("pageerror", error => errors.push(error.message));
    tab.on("response", response => {
      if (status === undefined && response.url().replace(/#.*$/, "") === url) status = response.status();
    });
    await tab.goto(url, { waitUntil: "load", timeout: options.timeout ?? 15_000 });
    const title = await tab.title();
    const healthy = await tab.evaluate(() =>
      fetch("/healthz").then(
        r => r.ok,
        () => false,
      ),
    );
    const screenshot = options.screenshot ? await tab.screenshot() : undefined;
    return {
      url,
      browser: browser.version(),
      title,
      status,
      healthy,
      errors,
      ...(screenshot ? { screenshot } : {}),
      ok: healthy && (status === undefined || status < 400) && errors.length === 0,
    };
  } finally {
    await browser.close();
  }
}

export const desktopScript = (c: TargetContext): string => `#!/usr/bin/env bun
// ${GENERATED_NOTE}
// ${c.name} in a desktop window: the compiled executable serves UI and API on a free loopback port and a
// Chrome-backed Bun.WebView window shows it. Closing the window stops the server.
//   bun desktop.ts [--executable ./${c.binary}] [--width 1280] [--height 800]
//   bun desktop.ts --smoke      headless check through @aphrody/bun-webview-page, JSON report, exit status
import { existsSync } from "node:fs";
import { join } from "node:path";
import { parseArgs } from "node:util";

const { values } = parseArgs({
  args: Bun.argv.slice(2),
  options: {
    executable: { type: "string", default: join(import.meta.dir, process.platform === "win32" ? ${JSON.stringify(`${c.binary}.exe`)} : ${JSON.stringify(c.binary)}) },
    width: { type: "string", default: "1280" },
    height: { type: "string", default: "800" },
    smoke: { type: "boolean", default: false },
  },
  strict: true,
});
if (!existsSync(values.executable)) throw new Error(\`missing \${values.executable} (${c.cli} compile)\`);

const probe = Bun.serve({ hostname: "127.0.0.1", port: 0, fetch: () => new Response() });
const port = probe.port;
await probe.stop(true);
const server = Bun.spawn([values.executable], {
  windowsHide: true,
  env: { ...process.env, PORT: String(port), HOST: "127.0.0.1" },
  stdout: "inherit",
  stderr: "inherit",
});
const url = \`http://127.0.0.1:\${port}/\`;
const deadline = Date.now() + 15_000;
while (!(await fetch(\`\${url}healthz\`).then((r) => r.ok, () => false))) {
  if (server.exitCode !== null || Date.now() > deadline) throw new Error(\`${c.name} did not answer on \${url}\`);
  await Bun.sleep(50);
}

if (values.smoke) {
  const { verifyWebView } = await import("@aphrody/m3-bun/targets");
  const report = await verifyWebView(url);
  console.log(JSON.stringify(report, null, 2));
  server.kill();
  process.exit(report.ok ? 0 : 1);
}

const view = new Bun.WebView({
  backend: { type: "chrome", url: false },
  headless: false,
  width: Number(values.width),
  height: Number(values.height),
});
const { promise: closed, resolve } = Promise.withResolvers<void>();
view.addEventListener("Target.detachedFromTarget", () => resolve());
process.once("SIGINT", () => view.close());
process.once("SIGTERM", () => view.close());
await view.navigate(url);
await Promise.race([closed, server.exited]);
view.close();
server.kill();
`;

const readme = (c: TargetContext): string => `<!-- ${GENERATED_NOTE} -->

# ${c.name}: desktop window

\`desktop.ts\` runs the compiled executable on a free loopback port and shows it in a Chrome-backed
\`Bun.WebView\` window, like the WebOS desktop of the Bun fork. Chrome (or Edge, Chromium, Brave) must be installed;
\`BUN_CHROME_PATH\` selects one.

\`\`\`sh
${c.cli} compile --outfile ./${c.binary}
bun desktop.ts            # the window
bun desktop.ts --smoke    # headless check: title, /healthz, console errors
\`\`\`

The WebOS shell (apps/desktop) has no external-app manifest: its apps are compiled into it, so ${c.name}
is not listed there.
`;

export const webos: Target = {
  id: "webos",
  title: "WebOS desktop window",
  description:
    "desktop.ts: the compiled app in a Chrome-backed Bun.WebView window, with a --smoke check through @aphrody/bun-webview-page",
  generate(c): TargetFile[] {
    return [
      { path: "desktop.ts", content: desktopScript(c), mode: 0o755 },
      { path: "README.md", content: readme(c) },
    ];
  },
};
