// Desktop themes in the app's colours, through @aphrody/m3-os-themes: Windows 11 (accent, wallpaper, .theme),
// GNOME Shell, COSMIC and Chromium browsers, all derived from the seed of `m3.config.ts`. The installers are
// generated next to their files and never run: the README lists the command of each one.
import { GENERATED_NOTE } from "../util.ts";
import type { Target, TargetContext, TargetFile } from "./types.ts";

const HOST = {
  windows: "win32",
  gnome: "linux",
  cosmic: "linux",
  chromium: "linux",
} as const;

async function load() {
  try {
    const [themes, cli] = await Promise.all([
      import("@aphrody/m3-os-themes"),
      import("@aphrody/m3-os-themes/cli"),
    ]);
    return {
      generate: themes.generate,
      targets: themes.TARGETS,
      installCommand: cli.installCommand,
    };
  } catch (error) {
    throw new Error(
      `m3-bun: the os-themes target needs @aphrody/m3-os-themes (${(error as Error).message})`,
      { cause: error },
    );
  }
}

/** `m3.config.ts` names are npm-like; theme names are `[A-Za-z0-9_-]+`. */
export const themeName = (name: string): string =>
  name.replace(/^@/, "").replace(/[^A-Za-z0-9_-]+/g, "-");

export async function generateOsThemes(
  c: TargetContext,
): Promise<TargetFile[]> {
  const { generate, targets, installCommand } = await load();
  const name = themeName(c.name);
  const seed = c.seed ?? "#6750a4";
  const files = generate({
    name,
    seed,
    mode: "auto",
    ...(c.variant ? { variant: c.variant as never } : {}),
  });
  const commands = targets.map((target) => {
    const { cmd, reason } = installCommand(
      target,
      ".",
      "auto",
      false,
      HOST[target],
    );
    return `- **${target}**: ${cmd.length > 0 ? `\`${cmd.join(" ").replaceAll("\\", "/")}\`` : reason}`;
  });
  const readme = `<!-- ${GENERATED_NOTE} -->

# ${c.name}: desktop themes

Generated by @aphrody/m3-os-themes from seed \`${seed}\`${c.variant ? ` (variant ${c.variant})` : ""}, light and dark,
active mode \`auto\`. Nothing is installed: run the installer of a desktop from this directory.

${commands.join("\n")}

Each installer takes \`--uninstall\` (\`-Uninstall\` on Windows). \`m3-os-themes install --target all --seed ${seed} --mode auto --apply\`
does the same in one step.
`;
  return [
    ...files.map(({ path, content, executable }): TargetFile =>
      executable ? { path, content, mode: 0o755 } : { path, content },
    ),
    { path: "README.md", content: readme },
  ];
}

export const osThemes: Target = {
  id: "os-themes",
  title: "Desktop themes",
  description:
    "Windows 11, GNOME Shell, COSMIC and Chromium themes from the app seed (@aphrody/m3-os-themes), with their installers",
  generate: generateOsThemes,
};
