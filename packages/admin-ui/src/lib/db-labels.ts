/** Convertit une clé de colonne en libellé lisible (fallback : prettify). */
export function colLabel(col: string): string {
  return (
    COL_LABELS[col] ??
    col
      .replace(/_/g, " ")
      .replace(/([A-Z])/g, " $1")
      .trim()
  );
}
