// Compaction of the crate's `animations.json` into the data a renderer needs. Pure, shared by
// scripts/generate.ts and the drift test.
import type { PetData, PetFrame, PetTrack } from "./pet";

interface RawRect {
  x: number;
  y: number;
  width: number;
  height: number;
}
interface RawFrame {
  atlasRect: RawRect;
  durationMs?: number;
}
interface RawAnimation {
  kind: string;
  frames: RawFrame[];
}
export interface RawAnimations {
  pet: { id: string; displayName: string; spriteVersionNumber: number };
  atlas: {
    width: number;
    height: number;
    cellWidth: number;
    cellHeight: number;
    columns: number;
    rows: number;
  };
  animations: Record<string, RawAnimation>;
}

const frame = (f: RawFrame): PetFrame => ({
  x: f.atlasRect.x,
  y: f.atlasRect.y,
  w: f.atlasRect.width,
  h: f.atlasRect.height,
  ms: f.durationMs ?? 0,
});

/** Keep the atlas geometry, the timed/still tracks and the gaze ring (clockwise from up). */
export function compactPet(raw: RawAnimations): PetData {
  const tracks: Record<string, PetTrack> = {};
  let directions: PetFrame[] = [];
  for (const [name, anim] of Object.entries(raw.animations)) {
    if (anim.kind === "directional-pose-set") {
      directions = anim.frames.map(frame);
    } else {
      tracks[name] = {
        kind: anim.kind === "still" ? "still" : "timed",
        frames: anim.frames.map(frame),
      };
    }
  }
  const { width, height, cellWidth, cellHeight, columns, rows } = raw.atlas;
  return {
    id: raw.pet.id,
    displayName: raw.pet.displayName,
    version: raw.pet.spriteVersionNumber,
    atlas: { width, height, cellWidth, cellHeight, columns, rows },
    tracks,
    directions,
  };
}

/** The TypeScript module written to src/animations.generated.ts. */
export function renderModule(data: PetData): string {
  return `// SPDX-License-Identifier: Apache-2.0
// GENERATED by \`bun scripts/generate.ts\` from crates/ui/identity/assets/aphrody/animations.json.
// Do not edit: src/pet.test.ts fails when this file drifts from the crate.
import type { PetData } from "./pet";

export const PET: PetData = ${JSON.stringify(data)};
`;
}
