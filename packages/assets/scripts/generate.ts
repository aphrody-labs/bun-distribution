// Generates `index.ts` in each asset folder, exporting every asset of the folder. Raster folders
// export default-imported URLs; SVG folders export React components (lazy-loaded in the
// `LAZY_FOLDERS`). Missing folders are skipped. The output is formatted with oxfmt.
//
//   bun run gen            # every folder
//   bun run gen -- icons   # only the listed folders

import { join } from "node:path";

const ASSET_FOLDERS = ["icons", "images", "videos"];
const LAZY_FOLDERS = ["svgs/brands", "svgs/ext/Extras", "svgs/ext/Code"];
const SKIP = new Set(["index.ts", "urls.ts"]);

const root = join(import.meta.dir, "..");

/** Names directly inside `dir` (files and folders, dotfiles included), or null when it is not a readable directory. */
const readdir = async (dir: string): Promise<string[] | null> => {
  const info = await Bun.file(dir)
    .stat()
    .catch(() => null);
  if (!info?.isDirectory()) return null;
  return Array.fromAsync(
    new Bun.Glob("*").scan({ cwd: dir, onlyFiles: false, dot: true }),
  ).catch(() => null);
};

/** `Video-20.png` → `Video20`. */
const variableName = (fileName: string): string =>
  fileName.split(".")[0]!.replaceAll("-", "");

/**
 * Canonical icon alias table: maps legacy/duplicate icon names to canonical
 * icon names so identical PNG binaries do not need to exist on disk.
 */
export const ICON_ALIASES: Record<string, string> = {
  DriveAmazonS3: "AmazonS3",
  DriveBackBlaze: "BackBlaze",
  DriveBox: "Box",
  DriveDAV: "DAV",
  DriveDropbox: "Dropbox",
  DriveGoogleDrive: "GoogleDrive",
  DrivePCloud: "PCloud",
  Executable: "Application",
  Executable_Light: "Application_Light",
  TextAlt: "Text",
};

function render(folder: string, lazy: boolean, fileNames: string[]): string {
  const imports = fileNames.map((fileName) => {
    const name = variableName(fileName);
    if (folder.startsWith("svgs")) {
      return lazy
        ? `const ${name} = React.lazy(async () => ({ default: (await import("./${fileName}")).ReactComponent }));`
        : `import { ReactComponent as ${name} } from "./${fileName}";`;
    }
    return `import ${name} from "./${fileName}";`;
  });

  const aliases =
    folder === "icons"
      ? Object.entries(ICON_ALIASES).map(
          ([alias, target]) => `const ${alias} = ${target};`,
        )
      : [];

  const exportNames = [
    ...fileNames.map(variableName),
    ...(folder === "icons" ? Object.keys(ICON_ALIASES) : []),
  ].toSorted();

  return [
    "/*",
    " * This file was automatically generated by a script.",
    " * To regenerate this file, run: bun run gen",
    " */",
    "",
    ...(lazy ? ['import React from "react";', ""] : []),
    ...imports,
    ...(aliases.length > 0 ? ["", ...aliases] : []),
    "",
    "export {",
    ...exportNames.map((name) => `  ${name},`),
    "};",
    "",
  ].join("\n");
}

async function generate(folder: string, lazy: boolean): Promise<string | null> {
  const dir = join(root, folder);
  const entries = await readdir(dir);
  if (!entries) return null;
  const fileNames = entries
    .filter((f) => !SKIP.has(f) && !f.startsWith("."))
    .toSorted();
  const out = join(dir, "index.ts");
  await Bun.write(out, render(folder, lazy, fileNames));
  return out;
}

/**
 * `svgs/ext/Extras/urls.ts`: the Bearded icon name → URL map, as explicit `?url` imports so any
 * bundler resolves it (no Vite-only `import.meta.glob`).
 */
async function generateBeardedUrls(): Promise<string | null> {
  const dir = join(root, "svgs/ext/Extras");
  const entries = await readdir(dir);
  if (!entries) return null;
  const svgs = entries.filter((f) => f.endsWith(".svg")).toSorted();
  const out = join(dir, "urls.ts");
  await Bun.write(
    out,
    [
      "/*",
      " * Bearded icon SVG URLs for use in interface package (web/desktop only).",
      " * This file was automatically generated by a script.",
      " * To regenerate this file, run: bun run gen",
      " */",
      "",
      ...svgs.map((f, i) => `import icon${i} from "./${f}?url";`),
      "",
      "export const beardedIconUrls: Record<string, string> = {",
      ...svgs.map((f, i) => `  ${JSON.stringify(f.slice(0, -4))}: icon${i},`),
      "};",
      "",
    ].join("\n"),
  );
  return out;
}

const only = new Set(Bun.argv.slice(2));
const folders: [string, boolean][] = [
  ...ASSET_FOLDERS.map((f): [string, boolean] => [f, false]),
  ...LAZY_FOLDERS.map((f): [string, boolean] => [f, true]),
].filter(([f]) => only.size === 0 || only.has(f));

const written = (
  await Promise.all([
    ...folders.map(([f, lazy]) => generate(f, lazy)),
    ...(only.size === 0 || only.has("svgs/ext/Extras")
      ? [generateBeardedUrls()]
      : []),
  ])
).filter((f): f is string => f !== null);
if (written.length > 0) {
  const fmt = Bun.spawnSync(["oxfmt", ...written], {
    windowsHide: true,
    stdout: "inherit",
    stderr: "inherit",
  });
  if (!fmt.success) process.exit(fmt.exitCode ?? 1);
}
console.log(`generated ${written.length} index file(s)`);
