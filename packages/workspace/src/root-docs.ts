import { readFileSync } from "node:fs";
import { join } from "node:path";

type Pair = [string, string];
type Row = [string, string, string];
/** Public sections are also rendered on aphrody.com by the selected Bun checkout's site collector. */
type Section = { id: string; title: string; public?: boolean; body: string[] };
type Data = {
  readme: {
    summary: string;
    sections?: Section[];
    installation?: string[];
    layout: Pair[];
    links: Pair[];
  };
  plan: {
    owners: Pair[];
    targets: Pair[];
    contracts: string[];
    queue: Pair[];
    success: string[];
    receipts: string;
  };
  memory: { intro: string; sections: { title: string; rows: Row[] }[] };
};

const HEADER = [
  "<!-- SPDX-License-Identifier: Apache-2.0 -->",
  "<!-- @generated by `yolo ops docs generate` from tools/config/docs/root.json (packages/infra/workspace/src/root-docs.ts). Edit the JSON, not this file. -->",
];

const cell = (s: string): string => s.replaceAll("|", "\\|");
const table = (head: string[], rows: string[][]): string[] => [
  `| ${head.join(" | ")} |`,
  `| ${head.map(() => "---").join(" | ")} |`,
  ...rows.map((r) => `| ${r.map(cell).join(" | ")} |`),
  "",
];
const finish = (lines: string[]): string => `${lines.join("\n").trimEnd()}\n`;

export const loadRootDocs = (root: string): Data =>
  JSON.parse(
    readFileSync(join(root, "tools/config/docs/root.json"), "utf8"),
  ) as Data;

export function renderReadme(d: Data, totals: string): string {
  return finish([
    ...HEADER,
    "# Aphrody",
    "",
    d.readme.summary,
    "",
    ...(d.readme.sections ?? []).flatMap((s) =>
      [`## ${s.title}`, ""].concat(s.body, ""),
    ),
    ...(d.readme.installation ?? []),
    "",
    "## Repository",
    "",
    totals,
    "",
    ...table(
      ["Path", "Content"],
      d.readme.layout.map(([p, t]) => [`\`${p}\``, t]),
    ),
    ...d.readme.links.map(([path, text]) => `- [${path}](${path}): ${text}`),
  ]);
}

export function renderPlan(d: Data): string {
  const p = d.plan;
  return finish([
    ...HEADER,
    "# Plan",
    "",
    "Architecture, contracts and open queue. Evidence: [MEMORY.md](MEMORY.md). Rules: [AGENTS.md](AGENTS.md).",
    "",
    "## Owners",
    "",
    ...table(["Owner", "Scope"], p.owners),
    "## Single surfaces",
    "",
    ...table(["Surface", "Target"], p.targets),
    "## Contracts",
    "",
    ...p.contracts.map((c) => `- ${c}`),
    "",
    "## Open queue",
    "",
    ...table(["Item", "Closure"], p.queue),
    "## Success",
    "",
    ...p.success.map((c) => `- [ ] ${c}`),
    "",
    p.receipts,
  ]);
}

export function renderMemory(d: Data): string {
  const m = d.memory;
  return finish([
    ...HEADER,
    "# Memory",
    "",
    m.intro,
    "",
    ...m.sections.flatMap((s) =>
      [`## ${s.title}`, ""].concat(
        table(["Date", "Evidence", "Limit"], s.rows),
      ),
    ),
  ]);
}
