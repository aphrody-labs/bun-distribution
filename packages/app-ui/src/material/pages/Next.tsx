import { useEffect, useState } from "react";
import { useM3Theme } from "@aphrody/m3-theme/react";
import { Card, Code, Page, Section } from "../ui.tsx";
import type { PageProps } from "./index.ts";

interface NextOutput {
  metadata: unknown;
  viewport: unknown;
  schemeCss: string;
  config: unknown;
  robots: string;
  sitemap: string;
  jsonLd: string;
}
export default function Next({ adaptive }: PageProps) {
  const { seedColor } = useM3Theme();
  const [result, setResult] = useState<NextOutput | null>(null);
  const [notice, setNotice] = useState("");
  const [selected, setSelected] = useState<keyof NextOutput>("metadata");
  useEffect(() => {
    const controller = new AbortController();
    // oxlint-disable-next-line react/set-state-in-effect -- the loading notice must reset for each seed before its request starts
    setNotice("Computing Next integration output…");
    void fetch("/api/next?seed=" + encodeURIComponent(seedColor), {
      signal: controller.signal,
    })
      .then(async (response) => {
        const payload = await response.json();
        if (!response.ok)
          throw new Error(payload.error ?? "Next output is unavailable.");
        if (!controller.signal.aborted) {
          setResult(payload as NextOutput);
          setNotice("Generated from the current theme and this site's origin.");
        }
        return payload;
      })
      .catch((error: unknown) => {
        if (!controller.signal.aborted)
          setNotice(
            error instanceof Error
              ? error.message
              : "Next output is unavailable.",
          );
      });
    return () => controller.abort();
  }, [seedColor]);
  const output = result?.[selected];
  return (
    <Page
      title="Next"
      summary="Explore metadata, viewport, theme sheets and crawler documents generated by the Next integration's public exports."
      packages={["@aphrody/m3-next"]}
      panes={adaptive.panes}
      aside={
        <Card>
          <h3 className="text-title-medium">App Router integration</h3>
          <Code>
            {
              'import { withM3 } from "@aphrody/m3-next";\nexport default withM3({});\n\nimport { generateM3Metadata, generateM3Viewport } from "@aphrody/m3-next";\nexport const metadata = generateM3Metadata({ name: "My app" });\nexport const viewport = generateM3Viewport();'
            }
          </Code>
        </Card>
      }
    >
      <Section
        title="Generated integration documents"
        description="Public helpers run in the standalone Bun host; the separate Next example qualifies its App Router host."
      >
        <Card className="flex flex-col gap-3">
          <label className="flex flex-col gap-2 text-label-large">
            Output
            <select
              className="h-12 rounded-small border border-outline bg-surface px-3"
              value={selected}
              onChange={(event) =>
                setSelected(event.target.value as keyof NextOutput)
              }
            >
              {(
                [
                  "metadata",
                  "viewport",
                  "schemeCss",
                  "config",
                  "robots",
                  "sitemap",
                  "jsonLd",
                ] as const
              ).map((name) => (
                <option key={name}>{name}</option>
              ))}
            </select>
          </label>
          <output className="block text-body-medium text-on-surface-variant">
            {notice}
          </output>
          <Code>
            {typeof output === "string"
              ? output
              : JSON.stringify(output ?? {}, null, 2)}
          </Code>
        </Card>
      </Section>
      {result ? (
        <Section title="Crawler files">
          <div className="grid gap-4 expanded:grid-cols-2">
            <Card>
              <h3 className="text-title-medium">robots.txt</h3>
              <Code>{result.robots}</Code>
            </Card>
            <Card>
              <h3 className="text-title-medium">sitemap.xml</h3>
              <Code>{result.sitemap}</Code>
            </Card>
          </div>
        </Section>
      ) : null}
    </Page>
  );
}
