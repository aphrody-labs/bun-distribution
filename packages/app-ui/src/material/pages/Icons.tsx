import { useEffect, useState } from "react";
import { Input } from "@aphrody/m3-primitives";
import home from "m3:icons/home";
import search from "m3:icons/search";
import favorite from "m3:icons/favorite";
import settings from "m3:icons/settings";
import download from "m3:icons/download";
import palette from "m3:icons/palette";
import dark from "m3:icons/dark_mode";
import light from "m3:icons/light_mode";
import close from "m3:icons/close";
import check from "m3:icons/check";
import menu from "m3:icons/menu";
import folder from "m3:icons/folder";
import { Card, Page, Section, Svg } from "../ui.tsx";
import type { PageProps } from "./index.ts";

const ICONS = [
  ["home", home],
  ["search", search],
  ["favorite", favorite],
  ["settings", settings],
  ["download", download],
  ["palette", palette],
  ["dark_mode", dark],
  ["light_mode", light],
  ["close", close],
  ["check", check],
  ["menu", menu],
  ["folder", folder],
] as const;
const TYPEFACES = ["Google Sans Flex", "Google Sans Code", "Roboto Mono"] as const;

export default function Icons({ adaptive }: PageProps) {
  const [searchTerm, setSearch] = useState("");
  const [selected, setSelected] = useState("home");
  const [sample, setSample] = useState("Aphrody · Material 3 · 0123456789");
  const [font, setFont] = useState<string>("Google Sans Flex");
  const [fontState, setFontState] = useState("Loading optional fonts…");
  useEffect(() => {
    let active = true;
    // The faces are declared by @aphrody/m3-fonts/fonts.css (imported by the app stylesheet).
    Promise.all(TYPEFACES.map(family => document.fonts.load(`16px "${family}"`)))
      .then(loaded => {
        if (!active) return undefined;
        const missing = TYPEFACES.filter((_, index) => loaded[index]!.length === 0);
        setFontState(
          missing.length
            ? `Not declared by @aphrody/m3-fonts: ${missing.join(", ")}; the system fallback renders them.`
            : "Loaded from @aphrody/m3-fonts; no external font service is used.",
        );
        return undefined;
      })
      .catch((error: unknown) => {
        if (active) setFontState(error instanceof Error ? error.message : String(error));
      });
    return () => {
      active = false;
    };
  }, []);
  const matches = ICONS.filter(([name]) => name.includes(searchTerm.trim().toLowerCase()));
  return (
    <Page
      title="Icons and fonts"
      summary="Per-icon Material Symbols SVG modules generated by the native build owner. Typefaces come from the @aphrody/m3-fonts sheet; no external font service is used."
      packages={["@aphrody/m3-icons", "@aphrody/m3-fonts", "@aphrody/material-design-icons"]}
      panes={adaptive.panes}
    >
      <Section
        title="Material Symbols"
        description="Choose a named SVG icon. The icon graphics are decorative inside labelled buttons."
      >
        <Input
          aria-label="Filter icons"
          placeholder="Filter icon names…"
          value={searchTerm}
          onChange={event => setSearch(event.target.value)}
        />
        <div className="grid grid-cols-2 gap-3 medium:grid-cols-4 expanded:grid-cols-6">
          {matches.map(([name, icon]) => (
            <button
              key={name}
              type="button"
              aria-pressed={name === selected}
              onClick={() => setSelected(name)}
              className={`state-layer flex min-h-28 flex-col items-center justify-center gap-3 rounded-medium p-3 ${name === selected ? "bg-secondary-container text-on-secondary-container" : "bg-surface-container text-on-surface"}`}
            >
              <Svg html={icon} />
              <span className="text-label-large">{name}</span>
            </button>
          ))}
        </div>
        <output className="block text-body-medium">
          {matches.length ? `Selected icon: ${selected}` : "No icons match this filter."}
        </output>
      </Section>
      <Section title="Typeface preview" description={fontState}>
        <Card className="flex flex-col gap-4">
          <label className="flex flex-col gap-2 text-label-large">
            Typeface
            <select
              value={font}
              onChange={event => setFont(event.target.value)}
              className="rounded-small border border-outline bg-surface p-3"
            >
              {TYPEFACES.map(family => (
                <option key={family}>{family}</option>
              ))}
            </select>
          </label>
          <Input aria-label="Sample text" value={sample} onChange={event => setSample(event.target.value)} />
          <p
            className="break-words text-headline-medium"
            style={{
              fontFamily: `"${font}", ${font === "Google Sans Flex" ? "sans-serif" : "monospace"}`,
            }}
          >
            {sample}
          </p>
        </Card>
      </Section>
    </Page>
  );
}
