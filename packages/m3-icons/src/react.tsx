import { useMemo } from "react";
import { m3Icon, type M3IconStyle } from "@aphrody/bun";

export interface M3IconProps {
  /** Material Symbols icon name, e.g. `"home"`, `"favorite"`. */
  name: string;
  /** Defaults to `"outlined"`. */
  style?: M3IconStyle;
  /** `FILL` axis, `0..1`. Defaults to `0`. */
  fill?: number;
  /** `wght` axis, `100..700`. Defaults to `400`. */
  weight?: number;
  /** `GRAD` axis, `-25..200`. Defaults to `0`. */
  grade?: number;
  /** `opsz` axis, `20..48`. Defaults to `24`. */
  opticalSize?: number;
  /** `width`/`height` in CSS pixels. Defaults to `24`. */
  size?: number;
  /** Accessible name; renders `role="img"` with `aria-label` when set, `aria-hidden` otherwise. */
  title?: string;
  className?: string;
}

/**
 * Renders a Material Symbols icon as inline SVG, generated from the variable font outlines by
 * the `icons` module of `aphrody-bun` through `@aphrody/bun` (no icon font requested, loaded or applied via CSS).
 */
export function M3Icon({
  name,
  style,
  fill,
  weight,
  grade,
  opticalSize,
  size,
  title,
  className,
}: M3IconProps) {
  const svg = useMemo(
    () => m3Icon({ name, style, fill, weight, grade, opticalSize, size }),
    [name, style, fill, weight, grade, opticalSize, size],
  );
  return (
    <span
      className={className}
      role={title ? "img" : undefined}
      aria-label={title}
      aria-hidden={title ? undefined : true}
      // biome-ignore lint: the SVG string is generated by the aphrody-bun icons module from font outlines, not user input.
      dangerouslySetInnerHTML={{ __html: svg }}
    />
  );
}
