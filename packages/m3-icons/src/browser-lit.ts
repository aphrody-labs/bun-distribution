//! Browser-safe Lit element: renders SVG produced ahead of time (`./codegen`, the
//! `m3:icon/` plugin or a server call to `m3Icon`). Nothing here reaches `@aphrody/bun`.

import { html, LitElement, nothing } from "lit";
import { customElement, property } from "lit/decorators.js";
import { unsafeHTML } from "lit/directives/unsafe-html.js";

/**
 * `<m3-icon-svg>`: inlines pre-generated Material Symbols SVG.
 *
 * ```html
 * <m3-icon-svg title="Home"></m3-icon-svg>
 * ```
 * Set the `svg` property (not an attribute) to the generated markup.
 */
@customElement("m3-icon-svg")
export class M3IconSvgElement extends LitElement {
  /** Complete `<svg>` markup generated by `m3Icon`, `./codegen` or the `m3:icon/` plugin. */
  @property({ attribute: false }) accessor svg = "";
  @property({ type: String }) accessor title = "";

  protected override createRenderRoot() {
    // Light DOM so the SVG inherits `currentColor` and font-size from the host document.
    return this;
  }

  override render() {
    if (!this.svg) return nothing;
    return html`${
      this.title
        ? html`<span role="img" aria-label=${this.title}>${unsafeHTML(this.svg)}</span>`
        : html`<span aria-hidden="true">${unsafeHTML(this.svg)}</span>`
    }`;
  }
}

declare global {
  interface HTMLElementTagNameMap {
    "m3-icon-svg": M3IconSvgElement;
  }
}
