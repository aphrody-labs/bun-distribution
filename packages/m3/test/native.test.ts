// The real `m3Css` of `@aphrody/bun` (Rust, `bun_rs`). Skipped when the native library is not
// built on this machine (`cargo build --release -p aphrody-bun`).
import { describe, expect, test } from "bun:test";
import { join } from "node:path";
import { cssRequest, loadAphrodyBun, normalizeVariant } from "../src/native.ts";
import { m3Plugin } from "../src/plugin.ts";
import { m3Tokens } from "../src/tokens.ts";
import { REPO_ROOT, tempDir } from "./helpers.ts";

const native = await loadAphrodyBun().catch(() => undefined);
const hasM3Css = typeof native?.m3Css === "function";

describe("variant spelling", () => {
  test("camelCase SchemeVariant names become the Rust kebab-case names", () => {
    expect(normalizeVariant("tonalSpot")).toBe("tonal-spot");
    expect(normalizeVariant("tonal-spot")).toBe("tonal-spot");
    expect(normalizeVariant("vibrant")).toBe("vibrant");
    expect(normalizeVariant("fruitSalad")).toBe("fruit-salad");
    expect(cssRequest("scheme", { variant: "tonalSpot", dark: true })).toEqual({ sheet: "scheme", variant: "tonal-spot", dark: true });
  });
});

describe.skipIf(!hasM3Css)("m3Css through FFI", () => {
  test("m3Tokens renders a dark scheme from a seed", async () => {
    const css = await m3Tokens({ sheet: "scheme", seed: "#6750a4", variant: "tonalSpot", dark: true });
    expect(css).toContain("color-scheme: dark");
    expect(css).toMatch(/--md-sys-color-primary: #[0-9a-f]{6};/);
  });

  test("m3:theme.css is generated by Rust in a real build", async () => {
    await using tmp = await tempDir();
    const entry = join(tmp.dir, "entry.ts");
    await Bun.write(entry, 'import "m3:theme.css";\n');
    const result = await Bun.build({
      entrypoints: [entry],
      outdir: join(tmp.dir, "out"),
      plugins: [m3Plugin({ theme: { seed: "#336699", variant: "vibrant" }, root: REPO_ROOT, tailwind: false })],
    });
    expect(result.success).toBe(true);
    const css = await result.outputs.find((o) => o.path.endsWith(".css"))!.text();
    expect(css).toContain("--md-sys-color-primary");
  });
});
