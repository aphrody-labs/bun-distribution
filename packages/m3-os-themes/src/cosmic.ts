// COSMIC desktop: cosmic-theme ThemeBuilder values as RON, one file per key (the cosmic-config layout)
// plus a single importable `.ron` bundle. COSMIC derives the built Dark/Light theme from the builder.
import { rolesFor, unit, validate } from "./color.ts";
import type { GeneratedFile, Mode, Roles, ThemeInput } from "./types.ts";

const SUCCESS: Record<Mode, string> = { light: "#2e7d32", dark: "#81c784" };
const WARNING: Record<Mode, string> = { light: "#b26a00", dark: "#ffb74d" };

export const cosmicDir = (mode: Mode): string =>
  `com.system76.CosmicTheme.${mode === "dark" ? "Dark" : "Light"}.Builder/v1`;
export const MODE_DIR = "com.system76.CosmicTheme.Mode/v1";

const srgb = (c: string): string => {
  const u = unit(c);
  return `(red: ${u.red}, green: ${u.green}, blue: ${u.blue})`;
};
const srgba = (c: string, alpha = "1.000000"): string => {
  const u = unit(c);
  return `(red: ${u.red}, green: ${u.green}, blue: ${u.blue}, alpha: ${alpha})`;
};

/** Builder keys (cosmic-config file names) mapped to RON values. */
export function builderEntries(roles: Roles, mode: Mode): Record<string, string> {
  return {
    accent: `Some(${srgb(roles["primary"]!)})`,
    bg_color: `Some(${srgba(roles["surface"]!)})`,
    primary_container_bg: `Some(${srgba(roles["surfaceContainer"]!)})`,
    secondary_container_bg: `Some(${srgba(roles["surfaceContainerHigh"]!)})`,
    neutral_tint: `Some(${srgb(roles["surfaceVariant"]!)})`,
    text_tint: `Some(${srgb(roles["onSurface"]!)})`,
    success: `Some(${srgb(SUCCESS[mode])})`,
    warning: `Some(${srgb(WARNING[mode])})`,
    destructive: `Some(${srgb(roles["error"]!)})`,
    window_hint: `Some(${srgb(roles["primary"]!)})`,
  };
}

/** Importable bundle (cosmic-settings > Appearance > Import) holding the same values. */
export function themeBundle(roles: Roles, mode: Mode, name: string): string {
  const body = Object.entries(builderEntries(roles, mode))
    .map(([k, v]) => `    ${k}: ${v},`)
    .join("\n");
  return `// M3-${name} (${mode}): generated by @aphrody/m3-os-themes\n(\n${body}\n)\n`;
}

export function installScript(input: ThemeInput): string {
  const name = input.name;
  return `#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
# Generated by @aphrody/m3-os-themes: M3-${name} for COSMIC (seed ${validate(input)}).
# Idempotent: the first run snapshots every key it overwrites; re-running keeps the snapshot.
# Reversible: ./install-cosmic.sh --uninstall. Flags: --mode auto|light|dark, --icons <freedesktop theme dir>, --dry-run.
set -euo pipefail
MODE="${input.mode}"
ICONS=""
UNINSTALL=0
DRY=0
while [ $# -gt 0 ]; do
  case "$1" in
    --mode) MODE="$2"; shift ;;
    --icons) ICONS="$2"; shift ;;
    --uninstall) UNINSTALL=1 ;;
    --dry-run) DRY=1 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
  shift
done
HERE="$(cd "$(dirname "$0")" && pwd)"
CONF="\${XDG_CONFIG_HOME:-$HOME/.config}/cosmic"
DATA="\${XDG_DATA_HOME:-$HOME/.local/share}"
BACKUP="$DATA/m3-os-themes/cosmic-${name}"
ICON_KEY="$CONF/com.system76.CosmicTk/v1/icon_theme"
run() { if [ "$DRY" = 1 ]; then echo "[dry-run] $*"; else "$@"; fi; }

case "$MODE" in auto|light|dark) ;; *) echo "unknown mode: $MODE" >&2; exit 2 ;; esac
if [ -n "$ICONS" ] && [ "$UNINSTALL" = 0 ]; then
  [ -f "$ICONS/index.theme" ] || { echo "--icons: $ICONS has no index.theme" >&2; exit 2; }
  ICON_NAME="$(basename "$ICONS")"
  case "$ICON_NAME" in ""|.|..|*[!a-zA-Z0-9_.\\ -]*) echo "invalid icon directory name: $ICON_NAME" >&2; exit 2 ;; esac
fi

# every generated key: <relative dir>/<key>
keys() { (cd "$HERE/config" && find . -type f | sed 's|^\\./||' | sort); }

if [ "$UNINSTALL" = 1 ]; then
  [ -d "$BACKUP" ] || { echo "No snapshot at $BACKUP: nothing to restore."; exit 0; }
  while read -r k; do
    if [ -f "$BACKUP/had/$k" ]; then run cp "$BACKUP/had/$k" "$CONF/$k"; else run rm -f "$CONF/$k"; fi
  done < <(keys)
  if [ -f "$BACKUP/icon_name" ]; then
    if [ -f "$BACKUP/icon_theme.had" ]; then run cp "$BACKUP/icon_theme.had" "$ICON_KEY"; else run rm -f "$ICON_KEY"; fi
    ICON_NAME="$(cat "$BACKUP/icon_name")"
    case "$ICON_NAME" in ""|.|..|*[!a-zA-Z0-9_.\\ -]*) echo "invalid icon snapshot name" >&2; exit 2 ;; esac
    run rm -rf "$DATA/icons/$ICON_NAME"
    if [ -e "$BACKUP/icon-dir.had" ]; then run cp -a "$BACKUP/icon-dir.had" "$DATA/icons/$ICON_NAME"; fi
  fi
  run rm -rf "$BACKUP"
  echo "M3-${name} removed; previous COSMIC theme restored."
  exit 0
fi

if [ -n "$ICONS" ] && [ -f "$BACKUP/icon_name" ] && [ "$(cat "$BACKUP/icon_name")" != "$ICON_NAME" ]; then
  echo "uninstall before changing the installed icon directory" >&2; exit 2
fi
if [ ! -d "$BACKUP" ] && [ "$DRY" = 0 ]; then
  mkdir -p "$BACKUP/had"
  while read -r k; do
    if [ -f "$CONF/$k" ]; then mkdir -p "$BACKUP/had/$(dirname "$k")"; cp "$CONF/$k" "$BACKUP/had/$k"; fi
  done < <(keys)
fi
while read -r k; do
  case "$MODE" in
    light) case "$k" in *Dark.Builder*) continue ;; esac ;;
    dark) case "$k" in *Light.Builder*) continue ;; esac ;;
  esac
  if [ "$k" = "${MODE_DIR}/is_dark" ] && [ "$MODE" = auto ]; then continue; fi
  run mkdir -p "$CONF/$(dirname "$k")"
  if [ "$k" = "${MODE_DIR}/is_dark" ]; then
    if [ "$DRY" = 1 ]; then echo "[dry-run] write $CONF/$k"; elif [ "$MODE" = dark ]; then printf true > "$CONF/$k"; else printf false > "$CONF/$k"; fi
  else
    run cp "$HERE/config/$k" "$CONF/$k"
  fi
done < <(keys)
if [ -n "$ICONS" ]; then
  [ -f "$ICONS/index.theme" ] || { echo "--icons: $ICONS has no index.theme (bun packages/material-design-icons/scripts/export-theme.ts)" >&2; exit 2; }
  ICON_NAME="$(basename "$ICONS")"
  if [ ! -f "$BACKUP/icon_name" ] && [ "$DRY" = 0 ]; then
    mkdir -p "$BACKUP"
    if [ -e "$DATA/icons/$ICON_NAME" ]; then cp -a "$DATA/icons/$ICON_NAME" "$BACKUP/icon-dir.had"; fi
    printf %s "$ICON_NAME" > "$BACKUP/icon_name"
    if [ -f "$ICON_KEY" ]; then cp "$ICON_KEY" "$BACKUP/icon_theme.had"; fi
  fi
  run mkdir -p "$DATA/icons" "$(dirname "$ICON_KEY")"
  run rm -rf "$DATA/icons/$ICON_NAME"
  run cp -r "$ICONS" "$DATA/icons/$ICON_NAME"
  if [ "$DRY" = 1 ]; then echo "[dry-run] write $ICON_KEY"; else printf '"%s"' "$ICON_NAME" > "$ICON_KEY"; fi
fi
echo "M3-${name} applied ($MODE). Restore with: $0 --uninstall"
`;
}

export function generateCosmic(input: ThemeInput): GeneratedFile[] {
  const files: GeneratedFile[] = [];
  const add = (path: string, content: string, executable = false): void => {
    files.push({
      target: "cosmic",
      path: `cosmic/${path}`,
      content,
      executable,
    });
  };
  for (const mode of ["dark", "light"] as const) {
    const { roles } = rolesFor(input, mode);
    for (const [key, value] of Object.entries(builderEntries(roles, mode))) {
      add(`config/${cosmicDir(mode)}/${key}`, value);
    }
    add(`M3-${input.name}-${mode}.ron`, themeBundle(roles, mode, input.name));
  }
  add(`config/${MODE_DIR}/is_dark`, input.mode === "light" ? "false" : "true");
  add("install-cosmic.sh", installScript(input), true);
  return files;
}
