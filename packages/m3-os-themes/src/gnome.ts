export function indexTheme(name: string): string {
  return `[Desktop Entry]
Type=X-GNOME-Metatheme
Name=M3-${name}
Comment=Material 3 theme generated from a seed colour
Encoding=UTF-8

[X-GNOME-Metatheme]
GtkTheme=M3-${name}
MetacityTheme=Adwaita
IconTheme=Adwaita
CursorTheme=Adwaita
`;
}

export function installScript(input: ThemeInput): string {
  const name = input.name;
  const accent = (m: Mode): string => nearestGnomeAccent(rolesFor(input, m).roles["primary"]!);
  return `#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
# Generated by @aphrody/m3-os-themes: M3-${name} for GNOME (seed ${validate(input)}).
# Idempotent: the first run snapshots the current gsettings and ~/.config/gtk-4.0/gtk.css; re-running keeps the snapshot.
# Reversible: ./install-gnome.sh --uninstall restores it. Flags: --mode auto|light|dark, --dry-run.
set -euo pipefail
NAME="M3-${name}"
MODE="${input.mode}"
UNINSTALL=0
DRY=0
while [ $# -gt 0 ]; do
  case "$1" in
    --mode) MODE="$2"; shift ;;
    --uninstall) UNINSTALL=1 ;;
    --dry-run) DRY=1 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
  shift
done
HERE="$(cd "$(dirname "$0")" && pwd)"
DATA="\${XDG_DATA_HOME:-$HOME/.local/share}"
CONF="\${XDG_CONFIG_HOME:-$HOME/.config}"
THEME_DIR="$DATA/themes/$NAME"
STATE="$DATA/m3-os-themes"
SNAP="$STATE/gnome-$NAME.env"
GTK4_CSS="$CONF/gtk-4.0/gtk.css"
MARK="m3-os-themes marker"

run() { if [ "$DRY" = 1 ]; then echo "[dry-run] $*"; else "$@"; fi; }
gget() { gsettings get "$1" "$2" 2>/dev/null || true; }
gset() { if gsettings writable "$1" "$2" >/dev/null 2>&1; then run gsettings set "$1" "$2" "$3"; fi; }

if [ "$UNINSTALL" = 1 ]; then
  if [ -f "$SNAP" ]; then
    # shellcheck disable=SC1090
    . "$SNAP"
    [ -n "\${GTK_THEME:-}" ] && gset org.gnome.desktop.interface gtk-theme "$GTK_THEME"
    [ -n "\${COLOR_SCHEME:-}" ] && gset org.gnome.desktop.interface color-scheme "$COLOR_SCHEME"
    [ -n "\${ACCENT:-}" ] && gset org.gnome.desktop.interface accent-color "$ACCENT"
    [ -n "\${SHELL_THEME:-}" ] && gset org.gnome.shell.extensions.user-theme name "$SHELL_THEME"
  fi
  run rm -rf "$THEME_DIR"
  if [ -f "$GTK4_CSS" ] && grep -q "$MARK" "$GTK4_CSS"; then
    run rm -f "$GTK4_CSS"
    [ -f "$GTK4_CSS.m3bak" ] && run mv "$GTK4_CSS.m3bak" "$GTK4_CSS"
  fi
  run rm -f "$SNAP"
  echo "$NAME removed."
  exit 0
fi

run mkdir -p "$STATE" "$DATA/themes" "$CONF/gtk-4.0"
if [ ! -f "$SNAP" ] && [ "$DRY" = 0 ]; then
  {
    echo "GTK_THEME=$(gget org.gnome.desktop.interface gtk-theme)"
    echo "COLOR_SCHEME=$(gget org.gnome.desktop.interface color-scheme)"
    echo "ACCENT=$(gget org.gnome.desktop.interface accent-color)"
    echo "SHELL_THEME=$(gget org.gnome.shell.extensions.user-theme name)"
  } > "$SNAP"
fi

run rm -rf "$THEME_DIR"
run cp -r "$HERE/themes/$NAME" "$THEME_DIR"
if [ -f "$GTK4_CSS" ] && ! grep -q "$MARK" "$GTK4_CSS" && [ ! -f "$GTK4_CSS.m3bak" ]; then
  run cp "$GTK4_CSS" "$GTK4_CSS.m3bak"
fi
case "$MODE" in
  dark) run cp "$THEME_DIR/gtk-4.0/gtk-dark.css" "$GTK4_CSS" ;;
  *) run cp "$THEME_DIR/gtk-4.0/gtk.css" "$GTK4_CSS" ;;
esac

gset org.gnome.desktop.interface gtk-theme "'$NAME'"
case "$MODE" in
  dark) gset org.gnome.desktop.interface color-scheme "'prefer-dark'"; ACC="${accent("dark")}" ;;
  light) gset org.gnome.desktop.interface color-scheme "'prefer-light'"; ACC="${accent("light")}" ;;
  *) gset org.gnome.desktop.interface color-scheme "'default'"; ACC="${accent("light")}" ;;
esac
gset org.gnome.desktop.interface accent-color "'$ACC'"
if gsettings list-schemas 2>/dev/null | grep -qx org.gnome.shell.extensions.user-theme; then
  gset org.gnome.shell.extensions.user-theme name "'$NAME'"
else
  echo "note: enable the User Themes extension to apply the Shell theme ($NAME)." >&2
fi
echo "$NAME applied ($MODE). Restore with: $0 --uninstall"
`;
}

export function generateGnome(input: ThemeInput): GeneratedFile[] {
  const light = rolesFor(input, "light").roles;
  const dark = rolesFor(input, "dark").roles;
  const shellMode: Mode = input.mode === "light" ? "light" : "dark";
  const shell = shellMode === "light" ? light : dark;
  const base = `gnome/themes/M3-${input.name}`;
  const f = (path: string, content: string, executable = false): GeneratedFile => ({
    target: "gnome",
    path,
    content,
    executable,
  });
  return [
    f(`${base}/index.theme`, indexTheme(input.name)),
    f(`${base}/gnome-shell/gnome-shell.css`, shellCss(shell, shellMode)),
    f(`${base}/gtk-3.0/gtk.css`, gtkCss(light, 3)),
    f(`${base}/gtk-3.0/gtk-dark.css`, gtkCss(dark, 3)),
    f(`${base}/gtk-4.0/gtk.css`, gtkCss(light, 4)),
    f(`${base}/gtk-4.0/gtk-dark.css`, gtkCss(dark, 4)),
    f("gnome/install-gnome.sh", installScript(input), true),
  ];
}
