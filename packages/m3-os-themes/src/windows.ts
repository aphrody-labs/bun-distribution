// Windows 11: Personalize registry values (dark/light, accent), DWM accent, .theme files, wallpaper script.
import { abgr, allModes, argb, hex8, rgb, rolesFor, validate } from "./color.ts";
import { gradientPng } from "./png.ts";
import type { GeneratedFile, Mode, Roles, ThemeInput } from "./types.ts";

export const PERSONALIZE_KEY = "HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Themes\\Personalize";
export const DWM_KEY = "HKCU\\Software\\Microsoft\\Windows\\DWM";
export const ACCENT_KEY = "HKCU\\Software\\Microsoft\\Windows\\CurrentVersion\\Explorer\\Accent";

export interface RegistryValue {
  key: string;
  name: string;
  type: "DWord" | "Binary";
  value: number | number[];
}

/** AccentPalette: 8 RGBA swatches (light to dark) built from the primary tonal roles. */
export function accentPalette(roles: Roles): number[] {
  const swatches = [
    roles["primaryFixed"],
    roles["primaryFixedDim"],
    roles["inversePrimary"],
    roles["primary"],
    roles["primary"],
    roles["onPrimaryContainer"],
    roles["onPrimaryFixedVariant"],
    roles["onPrimaryFixed"],
  ];
  return swatches.flatMap(c => {
    const [red, green, blue] = rgb(c!);
    return [red, green, blue, 0];
  });
}

/** Registry values the installer writes for one mode. */
export function registryValues(input: ThemeInput, mode: Mode): RegistryValue[] {
  const { roles } = rolesFor(input, mode);
  const light = mode === "light" ? 1 : 0;
  const accent = roles["primary"]!;
  return [
    {
      key: PERSONALIZE_KEY,
      name: "AppsUseLightTheme",
      type: "DWord",
      value: light,
    },
    {
      key: PERSONALIZE_KEY,
      name: "SystemUsesLightTheme",
      type: "DWord",
      value: light,
    },
    { key: PERSONALIZE_KEY, name: "ColorPrevalence", type: "DWord", value: 1 },
    { key: DWM_KEY, name: "AccentColor", type: "DWord", value: abgr(accent) },
    {
      key: DWM_KEY,
      name: "ColorizationColor",
      type: "DWord",
      value: argb(accent, 0xc4),
    },
    {
      key: DWM_KEY,
      name: "ColorizationAfterglow",
      type: "DWord",
      value: argb(accent, 0xc4),
    },
    {
      key: DWM_KEY,
      name: "AccentColorInactive",
      type: "DWord",
      value: abgr(roles["surfaceVariant"]!),
    },
    { key: DWM_KEY, name: "ColorPrevalence", type: "DWord", value: 1 },
    {
      key: ACCENT_KEY,
      name: "AccentColorMenu",
      type: "DWord",
      value: abgr(accent),
    },
    {
      key: ACCENT_KEY,
      name: "StartColorMenu",
      type: "DWord",
      value: abgr(roles["primaryContainer"]!),
    },
    {
      key: ACCENT_KEY,
      name: "AccentPalette",
      type: "Binary",
      value: accentPalette(roles),
    },
  ];
}

const psValue = (v: RegistryValue): string =>
  v.type === "DWord" ? `0x${hex8(v.value as number)}` : `([byte[]](${(v.value as number[]).join(",")}))`;

function psRegistryTable(input: ThemeInput): string {
  const rows = (mode: Mode): string =>
    registryValues(input, mode)
      .map(
        v => `    @{ Path = 'HKCU:${v.key.slice(4)}'; Name = '${v.name}'; Type = '${v.type}'; Value = ${psValue(v)} }`,
      )
      .join("\n");
  return `$Light = @(\n${rows("light")}\n)\n$Dark = @(\n${rows("dark")}\n)`;
}

export function themeFile(input: ThemeInput, mode: Mode): string {
  const { roles } = rolesFor(input, mode);
  const [r, g, b] = rgb(roles["background"]!);
  return [
    "[Theme]",
    `DisplayName=M3 ${input.name} (${mode})`,
    "",
    "[Control Panel\\Desktop]",
    `Wallpaper=%LOCALAPPDATA%\\m3-os-themes\\wallpaper-${input.name}-${mode}.png`,
    "TileWallpaper=0",
    "WallpaperStyle=10",
    "Pattern=",
    "",
    "[Control Panel\\Colors]",
    `Background=${r} ${g} ${b}`,
    "",
    "[VisualStyles]",
    "Path=%SystemRoot%\\resources\\themes\\Aero\\Aero.msstyles",
    "ColorStyle=NormalColor",
    "Size=NormalSize",
    "AutoColors=0",
    `ColorizationColor=0X${hex8(argb(roles["primary"]!, 0xc4)).toUpperCase()}`,
    "",
    "[MasterThemeSelector]",
    "MTSM=RJSPBS",
    "",
  ].join("\r\n");
}

export function installScript(input: ThemeInput): string {
  const { name } = input;
  const light = rolesFor(input, "light").roles;
  const dark = rolesFor(input, "dark").roles;
  return `# SPDX-License-Identifier: Apache-2.0
# Generated by @aphrody/m3-os-themes: M3-${name} for Windows 11 (seed ${validate(input)}).
# Idempotent: the first run snapshots the current values; re-running never overwrites that snapshot.
# Reversible: run with -Uninstall to restore the snapshot. Supports -WhatIf.
[CmdletBinding(SupportsShouldProcess)]
param(
    [ValidateSet('auto', 'light', 'dark')][string]$Mode = '${input.mode}',
    [switch]$Uninstall,
    [switch]$SkipWallpaper
)
$ErrorActionPreference = 'Stop'
$Name = '${name}'
$Home3 = Join-Path $env:LOCALAPPDATA 'm3-os-themes'
$Backup = Join-Path $Home3 "backup-$Name.json"
$WallpaperDir = $Home3

${psRegistryTable(input)}

if ($Mode -eq 'auto') {
    $current = (Get-ItemProperty 'HKCU:\\Software\\Microsoft\\Windows\\CurrentVersion\\Themes\\Personalize' -ErrorAction SilentlyContinue).AppsUseLightTheme
    $Mode = if ($current -eq 0) { 'dark' } else { 'light' }
}
$Values = if ($Mode -eq 'dark') { $Dark } else { $Light }
$WallpaperColors = @{
    light = @('${light["primaryContainer"]}', '${light["surface"]}')
    dark  = @('${dark["primaryContainer"]}', '${dark["surface"]}')
}

function Get-Current($v) {
    $item = Get-ItemProperty -Path $v.Path -Name $v.Name -ErrorAction SilentlyContinue
    if ($null -eq $item) { return $null }
    $item.($v.Name)
}

function Broadcast-Change {
    Add-Type -Namespace M3 -Name Native -MemberDefinition @'
[DllImport("user32.dll", SetLastError = true, CharSet = CharSet.Auto)]
public static extern IntPtr SendMessageTimeout(IntPtr hWnd, uint Msg, UIntPtr wParam, string lParam, uint flags, uint timeout, out UIntPtr result);
[DllImport("user32.dll", SetLastError = true, CharSet = CharSet.Auto)]
public static extern bool SystemParametersInfo(uint action, uint param, string value, uint flags);
'@ -ErrorAction SilentlyContinue
    $r = [UIntPtr]::Zero
    [void][M3.Native]::SendMessageTimeout([IntPtr]0xffff, 0x1A, [UIntPtr]::Zero, 'ImmersiveColorSet', 2, 5000, [ref]$r)
}

function Set-Wallpaper([string]$Path) {
    Add-Type -Namespace M3 -Name Native -MemberDefinition @'
[DllImport("user32.dll", SetLastError = true, CharSet = CharSet.Auto)]
public static extern bool SystemParametersInfo(uint action, uint param, string value, uint flags);
'@ -ErrorAction SilentlyContinue
    [void][M3.Native]::SystemParametersInfo(0x14, 0, $Path, 3)
}

function New-Wallpaper([string]$Path, [string]$Top, [string]$Bottom) {
    Add-Type -AssemblyName System.Drawing
    $bmp = New-Object System.Drawing.Bitmap 1920, 1080
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $rect = New-Object System.Drawing.Rectangle 0, 0, 1920, 1080
    $brush = New-Object System.Drawing.Drawing2D.LinearGradientBrush $rect, ([System.Drawing.ColorTranslator]::FromHtml($Top)), ([System.Drawing.ColorTranslator]::FromHtml($Bottom)), 90
    $g.FillRectangle($brush, $rect)
    $bmp.Save($Path, [System.Drawing.Imaging.ImageFormat]::Png)
    $brush.Dispose(); $g.Dispose(); $bmp.Dispose()
}

if ($Uninstall) {
    if (-not (Test-Path $Backup)) { Write-Host "No snapshot at $($Backup): nothing to restore."; return }
    $snap = Get-Content $Backup -Raw | ConvertFrom-Json
    foreach ($e in $snap.values) {
        if ($PSCmdlet.ShouldProcess("$($e.Path)\\$($e.Name)", 'restore')) {
            if ($null -eq $e.Value) { Remove-ItemProperty -Path $e.Path -Name $e.Name -ErrorAction SilentlyContinue }
            else {
                $val = if ($e.Type -eq 'Binary') { [byte[]]$e.Value } else { [int]$e.Value }
                if (-not (Test-Path $e.Path)) { New-Item -Path $e.Path -Force | Out-Null }
                Set-ItemProperty -Path $e.Path -Name $e.Name -Value $val -Type $e.Type
            }
        }
    }
    if ($snap.wallpaper -and -not $SkipWallpaper -and $PSCmdlet.ShouldProcess('wallpaper', 'restore')) { Set-Wallpaper $snap.wallpaper }
    if ($PSCmdlet.ShouldProcess($Backup, 'remove snapshot')) { Remove-Item $Backup -Force }
    Broadcast-Change
    Write-Host "M3-$Name removed; previous personalization restored."
    return
}

New-Item -ItemType Directory -Force -Path $Home3 | Out-Null
if (-not (Test-Path $Backup)) {
    $all = @($Light) + @($Dark) | Sort-Object { $_.Path + $_.Name } -Unique
    $snapValues = foreach ($v in $all) {
        $cur = Get-Current $v
        [pscustomobject]@{ Path = $v.Path; Name = $v.Name; Type = $v.Type; Value = $cur }
    }
    $wp = (Get-ItemProperty 'HKCU:\\Control Panel\\Desktop').WallPaper
    if ($PSCmdlet.ShouldProcess($Backup, 'write snapshot')) {
        [pscustomobject]@{ values = @($snapValues); wallpaper = $wp } | ConvertTo-Json -Depth 5 | Set-Content $Backup -Encoding UTF8
    }
}
foreach ($v in $Values) {
    if ($PSCmdlet.ShouldProcess("$($v.Path)\\$($v.Name)", "set $($v.Value)")) {
        if (-not (Test-Path $v.Path)) { New-Item -Path $v.Path -Force | Out-Null }
        Set-ItemProperty -Path $v.Path -Name $v.Name -Value $v.Value -Type $v.Type
    }
}
if (-not $SkipWallpaper) {
    $png = Join-Path $WallpaperDir "wallpaper-$Name-$Mode.png"
    $pair = $WallpaperColors[$Mode]
    if ($PSCmdlet.ShouldProcess($png, 'generate and set wallpaper')) {
        New-Wallpaper $png $pair[0] $pair[1]
        Set-Wallpaper $png
    }
}
Broadcast-Change
Write-Host "M3-$Name applied ($Mode). Restore with: .\\install-windows.ps1 -Uninstall"
`;
}

export function uninstallScript(): string {
  return `# SPDX-License-Identifier: Apache-2.0
# Restores the personalization snapshot taken by install-windows.ps1.
& (Join-Path $PSScriptRoot 'install-windows.ps1') -Uninstall @args
`;
}

export function generateWindows(input: ThemeInput): GeneratedFile[] {
  const files: GeneratedFile[] = [];
  const dir = "windows";
  for (const { mode, roles } of allModes(input)) {
    files.push({
      target: "windows",
      path: `${dir}/M3-${input.name}-${mode}.theme`,
      content: themeFile(input, mode),
    });
    files.push({
      target: "windows",
      path: `${dir}/wallpaper-${input.name}-${mode}.png`,
      content: gradientPng(64, 36, roles["primaryContainer"]!, roles["surface"]!),
    });
  }
  files.push({
    target: "windows",
    path: `${dir}/install-windows.ps1`,
    content: installScript(input),
  });
  files.push({
    target: "windows",
    path: `${dir}/uninstall-windows.ps1`,
    content: uninstallScript(),
  });
  return files;
}
