// Chromium-compatible browsers: Manifest V3 theme + BrowserThemeColor managed policy.
import { rgb, rolesFor, validate } from "./color.ts";
import { gradientPng } from "./png.ts";
import type { GeneratedFile, Mode, Roles, ThemeInput } from "./types.ts";

type Rgb = [number, number, number];

export interface ThemeManifest {
  manifest_version: 3;
  name: string;
  version: string;
  description: string;
  theme: {
    colors: Record<string, Rgb>;
    tints: Record<string, [number, number, number]>;
    images: Record<string, string>;
    properties: Record<string, string>;
  };
}

/** Browser policy directories (Linux) and registry hives (Windows) per browser. */
export const BROWSERS = {
  chrome: {
    linux: "/etc/opt/chrome/policies/managed",
    win: "SOFTWARE\\Policies\\Google\\Chrome",
  },
  chromium: {
    linux: "/etc/chromium/policies/managed",
    win: "SOFTWARE\\Policies\\Chromium",
  },
  brave: {
    linux: "/etc/brave/policies/managed",
    win: "SOFTWARE\\Policies\\BraveSoftware\\Brave",
  },
  edge: {
    linux: "/etc/opt/edge/policies/managed",
    win: "SOFTWARE\\Policies\\Microsoft\\Edge",
  },
} as const;

export function themeManifest(input: ThemeInput, mode: Mode): ThemeManifest {
  const { roles: r } = rolesFor(input, mode);
  const c = (k: string): Rgb => rgb(r[k]!);
  return {
    manifest_version: 3,
    name: `M3 ${input.name} (${mode})`,
    version: "1.0.0",
    description: `Material 3 ${mode} theme generated from ${validate(input)}`,
    theme: {
      colors: {
        frame: c("surfaceContainer"),
        frame_inactive: c("surface"),
        frame_incognito: c("surfaceContainerLowest"),
        frame_incognito_inactive: c("surfaceContainerLowest"),
        toolbar: c("surfaceContainerHigh"),
        tab_text: c("onSurface"),
        tab_background_text: c("onSurfaceVariant"),
        bookmark_text: c("onSurface"),
        ntp_background: c("surface"),
        ntp_text: c("onSurface"),
        ntp_link: c("primary"),
        button_background: c("primaryContainer"),
        omnibox_background: c("surfaceContainerHighest"),
        omnibox_text: c("onSurface"),
        toolbar_button_icon: c("onSurfaceVariant"),
        toolbar_text: c("onSurface"),
      },
      tints: {
        buttons: [-1, -1, -1],
        frame: [-1, -1, -1],
        frame_inactive: [-1, -1, -1],
        background_tab: [-1, -1, -1],
      },
      images: { theme_ntp_background: "images/ntp.png" },
      properties: {
        ntp_background_alignment: "bottom",
        ntp_background_repeat: "no-repeat",
      },
    },
  };
}

export function policyJson(roles: Roles): string {
  return `${JSON.stringify({ BrowserThemeColor: roles["primary"] }, null, 2)}\n`;
}

export function policyReg(roles: Roles): string {
  const lines = ["Windows Registry Editor Version 5.00", ""];
  for (const b of Object.values(BROWSERS)) {
    lines.push(
      `[HKEY_LOCAL_MACHINE\\${b.win}]`,
      `"BrowserThemeColor"="${roles["primary"]}"`,
      "",
    );
  }
  return lines.join("\r\n");
}

export function removeReg(): string {
  const lines = ["Windows Registry Editor Version 5.00", ""];
  for (const b of Object.values(BROWSERS)) {
    lines.push(`[HKEY_LOCAL_MACHINE\\${b.win}]`, `"BrowserThemeColor"=-`, "");
  }
  return lines.join("\r\n");
}

export function installScript(input: ThemeInput): string {
  const dirs = Object.entries(BROWSERS)
    .map(([b, v]) => `  ${b}) echo "${v.linux}" ;;`)
    .join("\n");
  return `#!/usr/bin/env bash
# SPDX-License-Identifier: Apache-2.0
# Generated by @aphrody/m3-os-themes: M3-${input.name} for Chromium browsers (seed ${validate(input)}).
# Installs the BrowserThemeColor managed policy (needs root) and prints how to load the theme unpacked.
# Usage: ./install-chromium.sh [--uninstall] [--dry-run] [--browser chrome|chromium|brave|edge|all] [--mode light|dark]
set -euo pipefail
UNINSTALL=0
DRY=0
BROWSER=all
MODE="${input.mode === "auto" ? "light" : input.mode}"
while [ $# -gt 0 ]; do
  case "$1" in
    --uninstall) UNINSTALL=1 ;;
    --dry-run) DRY=1 ;;
    --browser) BROWSER="$2"; shift ;;
    --mode) MODE="$2"; shift ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
  shift
done
HERE="$(cd "$(dirname "$0")" && pwd)"
run() { if [ "$DRY" = 1 ]; then echo "[dry-run] $*"; else "$@"; fi; }
policy_dir() {
  case "$1" in
${dirs}
  esac
}
for b in chrome chromium brave edge; do
  if [ "$BROWSER" != all ] && [ "$BROWSER" != "$b" ]; then continue; fi
  d="$(policy_dir "$b")"
  if [ "$UNINSTALL" = 1 ]; then
    run sudo rm -f "$d/m3-theme.json"
  else
    run sudo install -D -m 0644 "$HERE/policies/managed/m3-theme-$MODE.json" "$d/m3-theme.json"
  fi
done
if [ "$UNINSTALL" = 0 ]; then
  echo "Load the theme: open chrome://extensions (or brave://, edge://), enable Developer mode,"
  echo "choose Load unpacked, select: $HERE/$MODE"
  echo "Details: $HERE/install-chromium.md"
fi
`;
}

export function installDoc(input: ThemeInput): string {
  return `# M3-${input.name} for Chromium browsers

Generated by \`@aphrody/m3-os-themes\` from seed \`${validate(input)}\`.

## Theme (Chrome, Edge, Brave, Chromium)

1. Open \`chrome://extensions\` (\`edge://extensions\`, \`brave://extensions\`).
2. Enable **Developer mode**.
3. Choose **Load unpacked** and select \`light/\` or \`dark/\` (each holds a Manifest V3 \`manifest.json\` and \`images/\`).

\`--load-extension\` is not used: branded Chrome builds ignore it.

## Managed policy (toolbar/frame accent)

\`BrowserThemeColor\` is applied from \`policies/managed/m3-theme-<mode>.json\`.

- Linux: \`./install-chromium.sh [--browser chrome|chromium|brave|edge|all] [--mode light|dark]\`
  copies it to \`/etc/opt/chrome/policies/managed\`, \`/etc/chromium/policies/managed\`,
  \`/etc/brave/policies/managed\`, \`/etc/opt/edge/policies/managed\` with sudo.
  \`--uninstall\` removes it.
- Windows: import \`policies/windows/m3-theme-<mode>.reg\` (administrator); \`policies/windows/remove.reg\` reverts.

Check at \`chrome://policy\`. \`--dry-run\` prints the commands without running them.
`;
}

export function generateChromium(input: ThemeInput): GeneratedFile[] {
  const files: GeneratedFile[] = [];
  const add = (
    path: string,
    content: string | Uint8Array,
    executable = false,
  ): void => {
    files.push({
      target: "chromium",
      path: `chromium/${path}`,
      content,
      executable,
    });
  };
  for (const mode of ["light", "dark"] as const) {
    const { roles } = rolesFor(input, mode);
    add(
      `${mode}/manifest.json`,
      `${JSON.stringify(themeManifest(input, mode), null, 2)}\n`,
    );
    add(
      `${mode}/images/ntp.png`,
      gradientPng(1, 256, roles["surface"]!, roles["primaryContainer"]!),
    );
    add(`policies/managed/m3-theme-${mode}.json`, policyJson(roles));
    add(`policies/windows/m3-theme-${mode}.reg`, policyReg(roles));
  }
  add("policies/windows/remove.reg", removeReg());
  add("install-chromium.sh", installScript(input), true);
  add("install-chromium.md", installDoc(input));
  return files;
}
