// Collects the Material Symbols names the workspace's own apps and packages render through the
// icon font (ligature text), and writes them to src/symbols-subset.json: the glyph list of the
// default `fonts-symbols.css` subset (`bun run subset`). The full fonts stay in
// `fonts-symbols-full.css`.
//
//   bun scripts/symbols-names.ts [--check]
//
// A source file counts when it names the icon font (`material-symbols-*` class, `Material Symbols
// <Style>` family, `<md-icon>`, `--md-icon-font`) or imports @aphrody/m3-primitives (`<Icon>`).
// Every quoted string or element text in it that is a Material Symbols name of the pinned build
// (fonts/upstream/material-symbols/index.d.ts) is kept. Catalogue dumps (files naming more than
// MAX_PER_FILE symbols) and the icon packages themselves are skipped.
import { readdirSync } from "node:fs";
import { join, relative } from "node:path";

const pkg = join(import.meta.dir, "..");
const repo = join(pkg, "../..");
const out = join(pkg, "src/symbols-subset.json");
const MAX_PER_FILE = 300;
const SKIP_PACKAGES = new Set(["m3-fonts", "m3-icons", "m3-mcp", "material-design-icons", "m3-codemods"]);
const SKIP_DIRS = new Set([
  "node_modules",
  "dist",
  "ui-dist",
  "generated",
  "build",
  "out",
  "target",
  "vendor",
  "test",
  "tests",
  "__tests__",
  "__testfixtures__",
  "fixtures",
]);
const SOURCE = /\.(?:[cm]?[jt]sx?|html|vue|svelte)$/;
const USES_FONT =
  /material-symbols-(?:outlined|rounded|sharp)|Material Symbols (?:Outlined|Rounded|Sharp)|<md-icon\b|--md-icon-font|@aphrody\/m3-primitives/;

const declared = await Bun.file(join(pkg, "fonts/upstream/material-symbols/index.d.ts")).text();
const known = new Set([...declared.matchAll(/"([a-z0-9_]+)"/g)].map(m => m[1]!));
if (known.size < 1000) throw new Error("fonts/upstream is not synced: run `bun scripts/m3/fonts-sync.ts`");

function* sources(dir: string): Generator<string> {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (e.name.startsWith(".") || SKIP_DIRS.has(e.name) || e.isSymbolicLink()) continue;
    const p = join(dir, e.name);
    if (e.isDirectory()) yield* sources(p);
    else if (SOURCE.test(e.name) && !/\.(?:test|spec|stories)\.|^test-/.test(e.name)) yield p;
  }
}

const names = new Set<string>();
const used: string[] = [];
for (const group of ["apps", "packages"]) {
  for (const member of readdirSync(join(repo, group), { withFileTypes: true })) {
    if (!member.isDirectory() || (group === "packages" && SKIP_PACKAGES.has(member.name))) continue;
    for (const file of sources(join(repo, group, member.name))) {
      // oxlint-disable-next-line no-await-in-loop -- Sequential reads keep memory flat over the workspace.
      const text = await Bun.file(file).text();
      if (!USES_FONT.test(text)) continue;
      const hits = new Set(
        [...text.matchAll(/(?<=["'`>])([a-z0-9_]+)(?=["'`<])/g)].map(m => m[1]!).filter(n => known.has(n)),
      );
      if (hits.size === 0 || hits.size > MAX_PER_FILE) continue;
      for (const n of hits) names.add(n);
      used.push(relative(repo, file).replaceAll("\\", "/"));
    }
  }
}

const body = `${JSON.stringify(
  {
    $comment:
      "Generated by packages/m3-fonts/scripts/symbols-names.ts; do not edit. Material Symbols names rendered as icon-font ligatures by the workspace's apps and packages: the glyphs of the default fonts-symbols.css subset.",
    files: used.sort(),
    names: [...names].sort(),
  },
  null,
  2,
)}\n`;
if (process.argv.includes("--check")) {
  const current = await Bun.file(out)
    .text()
    .catch(() => "");
  if (current !== body) {
    console.error(`${relative(repo, out)} is stale: run \`bun run symbols:names\``);
    process.exit(1);
  }
} else {
  await Bun.write(out, body);
}
console.log(`${names.size} names from ${used.length} files`);
