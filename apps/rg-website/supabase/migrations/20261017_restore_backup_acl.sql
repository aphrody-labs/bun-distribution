-- Droits de l'API publique réalignés sur la dernière production.
--
-- La restauration a créé les objets sous `postgres` sur Supabase Cloud, dont
-- les privilèges par défaut accordent TOUT sur les tables et séquences de
-- `public` à `anon` et `authenticated`. Les restrictions de la production
