-- des GRANT explicites : sans ce réalignement, la clé publique lisait par
-- exemple `profiles.email`.
--
-- On retire donc tous les droits table/séquence des rôles de l'API, puis on
-- rejoue les GRANT exacts du dump de production (rôles self-host retirés).
-- `service_role` reste un rôle serveur à accès complet.

