-- Achillea unified database boundary.
--
-- The canonical database is `rg`; Achillea owns the `achillea` schema inside
-- it. This migration is deliberately idempotent and non-destructive: the
-- data copy/cutover is performed by scripts/ops/achillea-merge.ts after an
-- explicit inventory and backup.

create schema if not exists achillea;

comment on schema achillea is
  'Achillea domain tables in the unified Rose Griffon rg database';

create table if not exists achillea.sanction (
  id uuid primary key default gen_random_uuid(),
  user_id text not null,
  guild_id text not null,
  type text not null,
  reason text,
  duration_sec integer,
  issued_by text not null,
  issued_by_type text not null default 'staff',
  expires_at timestamptz,
  revoked_at timestamptz,
  revoked_by text,
  revoke_reason text,
  evidence jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists sanction_user_id_idx on achillea.sanction (user_id);
create index if not exists sanction_guild_user_idx on achillea.sanction (guild_id, user_id);
create index if not exists sanction_active_expiry_idx on achillea.sanction (expires_at)
  where revoked_at is null and expires_at is not null;

-- Notes staff : table métier non-Discord, consommée par le dashboard et le bot
-- uniquement comme adaptateur de commande. Les colonnes de relation restent des
-- identifiants pour permettre la migration indépendante des entités historiques.
create table if not exists achillea.player_note (
  id uuid primary key default gen_random_uuid(),
  target_id text not null,
  author_id text,
  tournament_id bigint,
  category text not null default 'other',
  severity text not null default 'info',
  content text not null,
  resolved boolean not null default false,
  resolved_at timestamptz,
  resolved_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists player_note_target_created_idx
  on achillea.player_note (target_id, created_at desc);
create index if not exists player_note_tournament_idx
  on achillea.player_note (tournament_id);

create table if not exists achillea.organization (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  name text not null,
  normalized_name text not null,
  logo text not null,
  description text not null,
  owner_id text not null,
  state integer not null default 0,
  preapproved boolean not null default false,
  preapproved_at timestamptz,
  preapproved_by text,
  twitter_url text,
  instagram_url text,
  tiktok_url text,
  twitch_url text,
  youtube_url text,
  origin text not null
);

create table if not exists achillea.organization_manager (
  organization_id bigint not null,
  user_id text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  primary key (organization_id, user_id)
);

do $$
declare
  role_name text;
begin
  foreach role_name in array array[
    'achillea_backend',
    'achillea_api',
    'achillea_storage',
    'achillea_realtime'
  ] loop
    if exists (select 1 from pg_roles where rolname = role_name) then
      execute format('grant usage on schema achillea to %I', role_name);
      execute format(
        'alter role %I in database %I set search_path = achillea, public',
        role_name,
        current_database()
      );
    end if;
  end loop;
end
$$;
