-- Canonical tournament lobby/match persistence.
--
-- These tables were historically owned by the Achillea MikroORM process. They
-- now live beside event/tournament_participant in the unified `achillea` schema
-- so score reporting and validation can be handled by the Elysia/Kysely API.

create table if not exists achillea.tournament_phase (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  tournament_id bigint not null references achillea.event(id) on delete cascade,
  "index" integer not null,
  kind text not null,
  config jsonb,
  status text not null default 'Pending',
  started_at timestamptz,
  ended_at timestamptz,
  qualifiers_count integer not null default 0
);

create index if not exists tournament_phase_tournament_idx
  on achillea.tournament_phase(tournament_id, "index");

create table if not exists achillea.event_managers (
  event_id bigint not null references achillea.event(id) on delete cascade,
  user_id text not null references achillea.user(id) on update cascade on delete cascade,
  primary key (event_id, user_id)
);

create table if not exists achillea.lobby (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  event_type text not null,
  event_id bigint not null references achillea.event(id) on delete cascade,
  mode smallint not null default 2,
  state text not null default 'Fresh',
  bracket_match_id bigint unique,
  channel_id text,
  host_user_id bigint,
  is_repool boolean not null default false,
  phase_id uuid references achillea.tournament_phase(id) on delete set null,
  swiss_round integer,
  match_format text not null default 'double_leg',
  custom_format_child_count integer,
  ranked_elo_applied boolean not null default false
);

create index if not exists lobby_event_idx on achillea.lobby(event_type, event_id);
create index if not exists lobby_state_idx on achillea.lobby(event_type, state);

create table if not exists achillea.lobby_user (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  user_id text not null references achillea.user(id) on update cascade,
  lobby_id bigint not null references achillea.lobby(id) on delete cascade,
  team smallint not null default 1,
  score integer not null default 0,
  forfeit boolean not null default false,
  elo_variation integer not null default 0,
  validated_result boolean not null default false,
  claimed_opponent_score integer,
  screenshot_url text,
  state text not null default 'Pending',
  unique (user_id, lobby_id)
);

create index if not exists lobby_user_lobby_idx on achillea.lobby_user(lobby_id, team);

create table if not exists achillea.lobby_match (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  lobby_id bigint not null references achillea.lobby(id) on delete cascade,
  game_number integer not null,
  score_team1 integer not null default 0,
  score_team2 integer not null default 0,
  team1validated boolean not null default false,
  team2validated boolean not null default false,
  admin_validated boolean not null default false,
  unique (lobby_id, game_number)
);

create index if not exists lobby_match_lobby_idx on achillea.lobby_match(lobby_id, game_number);

