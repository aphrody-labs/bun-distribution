import { join } from "node:path";
import { m3Icon, m3IconNames, type M3IconStyle } from "@aphrody/bun";

export interface GenerateIconsOptions {
  /** Icon names to emit. Defaults to every icon known for `style`. */
  names?: readonly string[];
  style?: M3IconStyle;
  fill?: number;
  weight?: number;
  grade?: number;
  opticalSize?: number;
  size?: number;
  outDir: string;
}

export interface GeneratedIcon {
  name: string;
  file: string;
}

/**
 * Build-time codegen: writes one tree-shakable ESM module per icon (`export default "<svg>"`)
 * into `outDir`, plus an `index.ts` barrel re-exporting each under its icon name. Apps that
 * `import icon from ".../icons/home.js"` (or the barrel, if their bundler tree-shakes unused
 * named exports) ship only the icons they actually use, instead of the whole Material Symbols
 * set or an icon font.
 */
export async function generateIcons(options: GenerateIconsOptions): Promise<GeneratedIcon[]> {
  const style = options.style ?? "outlined";
  const names = options.names ?? m3IconNames(style);

  const generated: GeneratedIcon[] = [];
  const barrelLines: string[] = [];
  for (const name of names) {
    const svg = m3Icon({
      name,
      style,
      fill: options.fill,
      weight: options.weight,
      grade: options.grade,
      opticalSize: options.opticalSize,
      size: options.size,
    });
    const identifier = toIdentifier(name);
    const file = join(options.outDir, `${name}.ts`);
    // oxlint-disable-next-line no-await-in-loop -- Emit each icon before adding its barrel export; bound writes and stop on failure.
    await Bun.write(
      file,
      `// Generated by @aphrody/m3-icons/codegen. Do not edit by hand.
export default ${JSON.stringify(svg)};
`,
    );
    barrelLines.push(`export { default as ${identifier} } from "./${name}.js";`);
    generated.push({ name, file });
  }

  const barrelContent = `// Generated by @aphrody/m3-icons/codegen. Do not edit by hand.\n${barrelLines.join("\n")}\n`;
  const barrelFile = join(options.outDir, "index.ts");
  await Bun.write(barrelFile, barrelContent);

  return generated;
}

function toIdentifier(name: string): string {
  const camel = name.replace(/_([a-z0-9])/g, (_, c: string) => c.toUpperCase());
  const safe = /^[0-9]/.test(camel) ? `icon${camel}` : camel;
  return safe;
}
