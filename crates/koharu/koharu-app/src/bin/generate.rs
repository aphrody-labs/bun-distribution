use anyhow::{Context as _, Result};
use specta_typescript::{Typescript, semantic::Configuration};

fn main() -> Result<()> {
    let output = std::env::var_os("KOHARU_PROTOCOL_OUT")
        .map(std::path::PathBuf::from)
        .unwrap_or_else(|| {
            std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
                .join("../../../packages/koharu/bridge/src/protocol.ts")
        });
    koharu_app::bindings()
        .semantic_types(Configuration::empty().enable_lossless_floats())
        .export(Typescript::default().header("// generated by koharu; do not edit\n"), &output)
        .with_context(|| format!("failed to generate {}", output.display()))?;
    Ok(())
}
