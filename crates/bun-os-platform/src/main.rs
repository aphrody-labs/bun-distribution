//! `bun-os-platform-native`: the native platform layer from the command line.
//!   t <locale> <domains,..> <key> [name=value...]   format a message (ICU4X numbers/dates)
//!   locale                                           negotiated chain and OS languages
//!   theme [id|path] [--light] [--high-contrast] [--seed #hex]   resolved tokens (JSON)
//!   tables                                           canonical M3 token tables (JSON)
//!   call <method> [json]                             one request to the Bun platform sidecar

use std::process::ExitCode;

use bun_os_platform::paths::Paths;
use bun_os_platform::{i18n, locale, sidecar, theme};

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let paths = Paths::discover();
    match args.first().map(String::as_str) {
        Some("t") if args.len() >= 4 => {
            let domains: Vec<&str> = args[2].split(',').collect();
            let (_, available) = locale::available(&paths);
            let (default, _) = locale::available(&paths);
            let tag = locale::lookup(&[args[1].clone()], &available).unwrap_or(default.clone());
            let l = i18n::Localizer::load(&paths, locale::chain(&tag, &available, &default), locale::Source::Override, &domains);
            let mut fluent = fluent_args(&args[4..]);
            println!("{}", l.format(&args[3], Some(&std::mem::take(&mut fluent))));
            for e in &l.errors {
                eprintln!("{e}");
            }
        }
        Some("locale") => {
            let (chain, source) = locale::negotiate(&paths, args.get(1).map(String::as_str));
            println!(
                "{}",
                serde_json::json!({ "chain": chain, "source": format!("{source:?}"), "os": locale::os_locales() })
            );
        }
        Some("theme") => {
            let id = args.get(1).filter(|a| !a.starts_with("--")).map(String::as_str);
            let file = match theme::load(&paths, id) {
                Ok(f) => f,
                Err(e) => {
                    eprintln!("{e}");
                    return ExitCode::FAILURE;
                }
            };
            let seed = args
                .iter()
                .position(|a| a == "--seed")
                .and_then(|i| args.get(i + 1))
                .and_then(|h| aphrody_m3_tokens::color_math::argb_from_hex(h));
            let tokens = theme::Tokens::resolve(
                &file,
                theme::ResolveOptions {
                    dark: args.iter().any(|a| a == "--light").then_some(false),
                    high_contrast: args.iter().any(|a| a == "--high-contrast"),
                    seed,
                    reduced_motion: args.iter().any(|a| a == "--reduced-motion"),
                },
            );
            println!("{}", serde_json::to_string_pretty(&tokens).unwrap_or_default());
        }
        Some("tables") => {
            // packages/bun-os-platform/themes/m3-tables.json: the token tables plus the state layers.
            let mut tables = serde_json::to_value(aphrody_m3_tokens::theme::export_token_tables()).unwrap_or_default();
            let state: serde_json::Map<String, serde_json::Value> = aphrody_m3_tokens::state::NAMES
                .iter()
                .zip(aphrody_m3_tokens::state::ALL)
                .map(|(n, s)| ((*n).to_string(), serde_json::json!(s.opacity)))
                .collect();
            tables["state"] = serde_json::Value::Object(state);
            tables["$comment"] = "Generated by `bun-os-platform-native tables` from crates/aphrody-m3-tokens (export_token_tables + state layers). Do not edit; regenerate.".into();
            println!("{}", serde_json::to_string_pretty(&tables).unwrap_or_default());
        }
        Some("call") if args.len() >= 2 => {
            let params = args.get(2).and_then(|p| serde_json::from_str(p).ok()).unwrap_or(serde_json::Value::Null);
            match sidecar::Sidecar::spawn(&paths.repo).map_err(|e| e.to_string()).and_then(|s| {
                s.call(&args[1], params, std::time::Duration::from_secs(120))
            }) {
                Ok(v) => println!("{}", serde_json::to_string_pretty(&v).unwrap_or_default()),
                Err(e) => {
                    eprintln!("{e}");
                    return ExitCode::FAILURE;
                }
            }
        }
        _ => {
            eprintln!("usage: bun-os-platform-native t <locale> <domains> <key> [k=v..] | locale [tag] | theme [id|path] [--light] [--high-contrast] [--seed #hex] | tables | call <method> [json]");
            return ExitCode::from(2);
        }
    }
    ExitCode::SUCCESS
}

fn fluent_args(pairs: &[String]) -> fluent_bundle::FluentArgs<'static> {
    let mut args = fluent_bundle::FluentArgs::new();
    for pair in pairs {
        if let Some((k, v)) = pair.split_once('=') {
            match v.parse::<f64>() {
                Ok(n) => args.set(k.to_string(), n),
                Err(_) => args.set(k.to_string(), v.to_string()),
            }
        }
    }
    args
}
