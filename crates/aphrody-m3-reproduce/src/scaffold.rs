//! Emits a runnable `@aphrody/m3` app skeleton from a [`crate::ReproductionPlan`]: `m3.config.ts`,
//! `src/index.html`, `src/App.tsx` and the plan's rendered `tokens.css`.
//!
//! The emitted app is intentionally minimal — a themed shell listing the detected component
//! landmarks — since turning a component list into full, content-populated M3 components is a
//! design decision the reproduction's author should review, not something to guess silently. See
//! `docs/design/M3-REPRODUCE.md` for the intended next step (`m3 new` scaffolding once
//! `@aphrody/m3`'s CLI, M3-PLAN.md phase 3, lands).

use std::{
    fs, io,
    path::{Path, PathBuf},
};

use crate::plan::ReproductionPlan;

fn m3_config_ts(plan: &ReproductionPlan) -> String {
    format!(
        "// SPDX-License-Identifier: Apache-2.0\n// Generated by aphrody-m3-reproduce. Seed \
         {seed} ({variant}, contrast {contrast}).\n// Rationale: {rationale}\nexport default {{\n  \
         theme: {{ seed: \"{seed}\", variant: \"{variant_lower}\", contrast: {contrast} }},\n}};\n",
        seed = plan.theme.seed_hex,
        variant = plan.theme.variant,
        variant_lower = plan.theme.variant.to_ascii_lowercase(),
        contrast = plan.theme.contrast,
        rationale = plan.theme.rationale,
    )
}

fn index_html(plan: &ReproductionPlan) -> String {
    let title = match &plan.source {
        crate::plan::ReproductionSource::Url { url } => url.clone(),
        crate::plan::ReproductionSource::Image { .. } => "Reproduced app (image seed)".to_owned(),
        crate::plan::ReproductionSource::Html => "Reproduced app".to_owned(),
    };
    format!(
        "<!DOCTYPE html>\n<html lang=\"en\">\n<head>\n  <meta charset=\"utf-8\">\n  <meta \
         name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n  \
         <title>{title}</title>\n  <link rel=\"stylesheet\" \
         href=\"./tokens.css\">\n</head>\n<body>\n  <div id=\"root\"></div>\n  <script \
         type=\"module\" src=\"./App.tsx\"></script>\n</body>\n</html>\n"
    )
}

fn component_list_tsx(plan: &ReproductionPlan) -> String {
    if plan.components.is_empty() {
        return "        <li>No layout landmarks detected (image-only reproduction).</li>\n"
            .to_owned();
    }
    plan.components
        .iter()
        .map(|c| {
            format!("        <li>{} — from <code>{}</code></li>\n", c.component, c.source_hint)
        })
        .collect()
}

fn app_tsx(plan: &ReproductionPlan) -> String {
    format!(
        "// SPDX-License-Identifier: Apache-2.0\n// Generated by aphrody-m3-reproduce — review \
         before shipping.\nimport {{ M3App }} from \"@aphrody/m3-primitives\";\n\nexport default \
         function App() {{\n  return (\n    <M3App>\n      <h1>Reproduced theme</h1>\n      \
         <p>Seed {seed} ({variant}). {rationale}</p>\n      <h2>Detected components</h2>\n      \
         <ul>\n{components}</ul>\n    </M3App>\n  );\n}}\n",
        seed = plan.theme.seed_hex,
        variant = plan.theme.variant,
        rationale = plan.theme.rationale,
        components = component_list_tsx(plan),
    )
}

/// Writes `m3.config.ts`, `src/index.html`, `src/App.tsx` and `tokens.css` under `out_dir`
/// (created if missing), plus `plan.json` (the plan itself, for review/regeneration).
///
/// # Errors
///
/// Returns [`crate::Error::Io`] on a filesystem failure, [`crate::Error::Json`] if the plan
/// cannot be serialized.
pub fn emit_scaffold(plan: &ReproductionPlan, out_dir: &Path) -> crate::Result<()> {
    fs::create_dir_all(out_dir)?;
    let src_dir = out_dir.join("src");
    fs::create_dir_all(&src_dir)?;

    write_file(&out_dir.join("m3.config.ts"), &m3_config_ts(plan))?;
    write_file(&out_dir.join("tokens.css"), &plan.theme.tokens_css)?;
    write_file(&src_dir.join("index.html"), &index_html(plan))?;
    write_file(&src_dir.join("App.tsx"), &app_tsx(plan))?;
    write_file(&out_dir.join("plan.json"), &plan.to_json()?)?;
    Ok(())
}

fn write_file(path: &PathBuf, contents: &str) -> io::Result<()> {
    fs::write(path, contents)
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::theme::theme_from_seed;

    fn sample_plan() -> ReproductionPlan {
        ReproductionPlan {
            source: crate::plan::ReproductionSource::Url { url: "https://example.com".to_owned() },
            theme: theme_from_seed(0xFF67_50A4, "test"),
            font_stacks: vec!["\"Google Sans\", sans-serif".to_owned()],
            corner_radius_dp: Some(16.0),
            components: vec![crate::plan::ComponentNode {
                component: "top-app-bar".to_owned(),
                source_hint: "header".to_owned(),
                text: None,
                children: Vec::new(),
            }],
            assets: Vec::new(),
        }
    }

    #[test]
    fn emits_every_expected_file() {
        let dir =
            std::env::temp_dir().join(format!("aphrody-m3-reproduce-test-{}", std::process::id()));
        let plan = sample_plan();
        emit_scaffold(&plan, &dir).expect("emit_scaffold");

        for rel in ["m3.config.ts", "tokens.css", "plan.json", "src/index.html", "src/App.tsx"] {
            let path = dir.join(rel);
            assert!(path.exists(), "missing {rel}");
        }
        let app_tsx = fs::read_to_string(dir.join("src/App.tsx")).unwrap();
        assert!(app_tsx.contains("top-app-bar"));
        assert!(app_tsx.contains("#6750a4"));

        fs::remove_dir_all(&dir).ok();
    }
}
