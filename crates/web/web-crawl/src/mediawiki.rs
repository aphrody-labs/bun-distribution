//! Bounded MediaWiki API enumeration and page extraction.
//!
//! This adapter uses the public Action API rather than scraping the rendered
//! wiki index. Listing and page parsing requests share one rate limit so large
//! prefixes do not accidentally fan out into an unbounded crawl.

use std::time::{Duration, Instant};

use crate::{CrawlTransport, FetchResult};
use aphrody_web_extract::{extract_main, html_to_markdown};
use obscura_net::ObscuraHttpClient;
use regex::Regex;
use serde_json::Value;
use url::Url;

/// Configuration for a bounded MediaWiki prefix crawl.
#[derive(Clone, Debug)]
pub struct MediaWikiOptions {
    /// Absolute URL of the wiki's `api.php` endpoint.
    pub api_url: Url,
    /// Article URL path with `$1` standing for the percent-encoded page title.
    /// Defaults to MediaWiki's common `/wiki/$1` path.
    pub article_path: String,
    /// Optional case-sensitive MediaWiki title prefix.
    pub prefix: Option<String>,
    /// Include only generated article URLs matching at least one expression.
    pub include_url_regex: Vec<String>,
    /// Reject generated article URLs matching any expression.
    pub exclude_url_regex: Vec<String>,
    /// Maximum number of pages returned, regardless of continuation length.
    pub max_pages: usize,
    /// Maximum titles requested from `allpages` in one API call.
    pub page_batch_size: usize,
    /// Minimum interval between all API requests, including page parsing.
    pub request_interval: Duration,
}

impl MediaWikiOptions {
    #[must_use]
    pub fn new(api_url: Url) -> Self {
        Self {
            api_url,
            article_path: "/wiki/$1".into(),
            prefix: None,
            include_url_regex: Vec::new(),
            exclude_url_regex: Vec::new(),
            max_pages: 200,
            page_batch_size: 50,
            request_interval: Duration::from_millis(250),
        }
    }
}

/// One page extracted through the MediaWiki parse API.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct MediaWikiDocument {
    pub page_id: u64,
    /// Normalized MediaWiki title: underscores become spaces and whitespace
    /// is trimmed, while the wiki's title casing is preserved.
    pub title: String,
    /// Absolute URL constructed from `article_path` and the normalized title.
    pub url: Url,
    /// Markdown generated by Aphrody Web's shared HTML extractor.
    pub markdown: String,
}

/// Errors encountered while enumerating or parsing MediaWiki pages.
#[derive(Debug)]
pub enum MediaWikiError {
    InvalidOptions(String),
    InvalidArticlePath(String),
    Http(String),
    HttpStatus { url: String, status: u16 },
    Api(String),
    InvalidResponse(String),
}

impl std::fmt::Display for MediaWikiError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::InvalidOptions(message) => write!(f, "invalid MediaWiki options: {message}"),
            Self::InvalidArticlePath(message) => {
                write!(f, "invalid MediaWiki article path: {message}")
            },
            Self::Http(message) => write!(f, "MediaWiki request failed: {message}"),
            Self::HttpStatus { url, status } => {
                write!(f, "MediaWiki request returned HTTP {status}: {url}")
            },
            Self::Api(message) => write!(f, "MediaWiki API error: {message}"),
            Self::InvalidResponse(message) => write!(f, "invalid MediaWiki response: {message}"),
        }
    }
}

impl std::error::Error for MediaWikiError {}

/// Enumerate all pages matching `prefix` and return at most `max_pages`
/// documents. Both enumeration and parse requests use the existing Obscura
/// HTTP client, with one shared minimum request interval.
pub async fn crawl_mediawiki(
    client: &ObscuraHttpClient,
    options: &MediaWikiOptions,
) -> Result<Vec<MediaWikiDocument>, MediaWikiError> {
    crawl_mediawiki_with_transport(&MediaWikiTransport(client), options).await
}

struct MediaWikiTransport<'a>(&'a ObscuraHttpClient);
impl CrawlTransport for MediaWikiTransport<'_> {
    async fn fetch(&self, url: &Url) -> Result<FetchResult, String> {
        let response = self.0.fetch(url).await.map_err(|error| error.to_string())?;
        Ok(FetchResult {
            url: response.url.clone(),
            status: response.status,
            content_type: response.content_type().map(str::to_owned),
            body: response.text(),
        })
    }
}

/// The same API crawler using an injectable capture/budget transport.
pub async fn crawl_mediawiki_with_transport<T: CrawlTransport>(
    client: &T,
    options: &MediaWikiOptions,
) -> Result<Vec<MediaWikiDocument>, MediaWikiError> {
    validate_options(options)?;
    let include = compile_patterns(&options.include_url_regex, "include")?;
    let exclude = compile_patterns(&options.exclude_url_regex, "exclude")?;
    if options.max_pages == 0 {
        return Ok(Vec::new());
    }

    let page_limit = options.max_pages.min(MAX_MEDIAWIKI_PAGES);
    let batch_size = options.page_batch_size.clamp(1, MAX_ALLPAGES_BATCH);
    let mut documents = Vec::with_capacity(page_limit.min(256));
    let mut continuation: Option<(String, String)> = None;
    let mut last_request = None;

    'enumeration: while documents.len() < page_limit {
        let remaining = page_limit - documents.len();
        let limit = batch_size.min(remaining);
        let mut params = vec![
            ("action", "query".to_owned()),
            ("format", "json".to_owned()),
            ("formatversion", "2".to_owned()),
            ("list", "allpages".to_owned()),
            ("aplimit", limit.to_string()),
        ];
        if let Some(prefix) = options.prefix.as_deref().filter(|prefix| !prefix.is_empty()) {
            params.push(("apprefix", prefix.to_owned()));
        }
        if let Some((apcontinue, generic_continue)) = continuation.as_ref() {
            params.push(("apcontinue", apcontinue.clone()));
            params.push(("continue", generic_continue.clone()));
        }

        let response =
            request_json_with_transport(client, options, &params, &mut last_request).await?;
        if let Some(error) = api_error(&response) {
            return Err(MediaWikiError::Api(error));
        }
        let pages = response
            .get("query")
            .and_then(|query| query.get("allpages"))
            .and_then(Value::as_array)
            .ok_or_else(|| MediaWikiError::InvalidResponse("query.allpages is missing".into()))?;

        let mut titles = Vec::with_capacity(pages.len());
        for page in pages {
            let title = page.get("title").and_then(Value::as_str).ok_or_else(|| {
                MediaWikiError::InvalidResponse("allpages entry has no title".into())
            })?;
            let page_id = page.get("pageid").and_then(Value::as_u64).ok_or_else(|| {
                MediaWikiError::InvalidResponse(format!("allpages entry {title:?} has no pageid"))
            })?;
            titles.push((normalize_title(title), page_id));
        }

        for (title, page_id) in titles {
            if documents.len() >= page_limit {
                break 'enumeration;
            }
            let page_url = article_url(options, &title)?;
            if !url_matches(&page_url, &include, &exclude) {
                continue;
            }
            let params = vec![
                ("action", "parse".to_owned()),
                ("format", "json".to_owned()),
                ("formatversion", "2".to_owned()),
                ("page", title.clone()),
                ("prop", "text".to_owned()),
            ];
            let parsed =
                request_json_with_transport(client, options, &params, &mut last_request).await?;
            if let Some(error) = api_error(&parsed) {
                return Err(MediaWikiError::Api(error));
            }
            let parse = parsed.get("parse").ok_or_else(|| {
                MediaWikiError::InvalidResponse(format!("parse result missing for {title:?}"))
            })?;
            let html = parse.get("text").and_then(Value::as_str).ok_or_else(|| {
                MediaWikiError::InvalidResponse(format!("parse.text missing for {title:?}"))
            })?;
            let extracted = extract_main(html, Some(page_url.as_str()));
            let markdown = if extracted.markdown.trim().is_empty() {
                html_to_markdown(html, Some(page_url.as_str()))
            } else {
                extracted.markdown
            };
            documents.push(MediaWikiDocument { page_id, title, url: page_url, markdown });
        }

        continuation = response.get("continue").and_then(|value| {
            Some((
                value.get("apcontinue")?.as_str()?.to_owned(),
                value.get("continue")?.as_str()?.to_owned(),
            ))
        });
        if continuation.is_none() || pages.is_empty() {
            break;
        }
    }

    Ok(documents)
}

const MAX_MEDIAWIKI_PAGES: usize = 10_000;
const MAX_ALLPAGES_BATCH: usize = 500;

pub(crate) fn validate_options(options: &MediaWikiOptions) -> Result<(), MediaWikiError> {
    if options.api_url.scheme() != "http" && options.api_url.scheme() != "https" {
        return Err(MediaWikiError::InvalidResponse("api_url must use HTTP or HTTPS".into()));
    }
    if !options.article_path.contains("$1") {
        return Err(MediaWikiError::InvalidArticlePath("expected a $1 title placeholder".into()));
    }
    if !options.article_path.starts_with('/')
        || options.article_path.starts_with("//")
        || options.article_path.contains('?')
        || options.article_path.contains('#')
    {
        return Err(MediaWikiError::InvalidArticlePath(
            "path must be rooted at the wiki origin and have no query or fragment".into(),
        ));
    }
    Ok(())
}

fn normalize_title(title: &str) -> String {
    title.replace('_', " ").trim().to_owned()
}

fn compile_patterns(patterns: &[String], kind: &str) -> Result<Vec<Regex>, MediaWikiError> {
    patterns
        .iter()
        .map(|pattern| {
            Regex::new(pattern).map_err(|error| {
                MediaWikiError::InvalidResponse(format!(
                    "invalid {kind} URL regex {pattern:?}: {error}"
                ))
            })
        })
        .collect()
}

fn url_matches(url: &Url, include: &[Regex], exclude: &[Regex]) -> bool {
    let value = url.as_str();
    !exclude.iter().any(|pattern| pattern.is_match(value))
        && (include.is_empty() || include.iter().any(|pattern| pattern.is_match(value)))
}

fn article_url(options: &MediaWikiOptions, title: &str) -> Result<Url, MediaWikiError> {
    let mut wiki_root = options.api_url.clone();
    wiki_root.set_query(None);
    wiki_root.set_fragment(None);
    // `api.php` is an endpoint, while an article path is rooted at the wiki.
    // Keep the installation prefix (`/w/api.php` -> `/wiki/...` is supplied
    // by article_path; `/wiki/$1` remains the MediaWiki default).
    let encoded_title = url::form_urlencoded::byte_serialize(title.as_bytes())
        .collect::<String>()
        .replace('+', "%20");
    let path = options.article_path.replace("$1", &encoded_title);
    wiki_root.join(&path).map_err(|error| MediaWikiError::InvalidArticlePath(error.to_string()))
}

pub(crate) async fn request_json(
    client: &ObscuraHttpClient,
    options: &MediaWikiOptions,
    params: &[(&str, String)],
    last_request: &mut Option<Instant>,
) -> Result<Value, MediaWikiError> {
    request_json_with_transport(&MediaWikiTransport(client), options, params, last_request).await
}

async fn request_json_with_transport<T: CrawlTransport>(
    client: &T,
    options: &MediaWikiOptions,
    params: &[(&str, String)],
    last_request: &mut Option<Instant>,
) -> Result<Value, MediaWikiError> {
    if let Some(previous) = last_request {
        let elapsed = previous.elapsed();
        if elapsed < options.request_interval {
            tokio::time::sleep(options.request_interval - elapsed).await;
        }
    }
    let mut url = options.api_url.clone();
    {
        let mut query = url.query_pairs_mut();
        query.clear();
        for (key, value) in params {
            query.append_pair(key, value);
        }
    }
    *last_request = Some(Instant::now());
    let response =
        client.fetch(&url).await.map_err(|error| MediaWikiError::Http(error.to_string()))?;
    if !(200..300).contains(&response.status) {
        return Err(MediaWikiError::HttpStatus { url: url.to_string(), status: response.status });
    }
    serde_json::from_str(&response.body)
        .map_err(|error| MediaWikiError::InvalidResponse(error.to_string()))
}

pub(crate) fn api_error(response: &Value) -> Option<String> {
    let error = response.get("error")?;
    let code = error.get("code").and_then(Value::as_str).unwrap_or("unknown");
    let info = error.get("info").and_then(Value::as_str).unwrap_or("no details");
    Some(format!("{code}: {info}"))
}
