//! Generate the TypeScript base projection from the canonical envelope schema.
use serde_json::Value;

fn typescript_type(schema: &Value) -> String {
    if schema.get("const").is_some_and(Value::is_number) {
        return "number".to_owned();
    }
    if let Some(values) = schema.get("enum").and_then(Value::as_array) {
        return values
            .iter()
            .map(Value::to_string)
            .collect::<Vec<_>>()
            .join(" | ");
    }
    match schema["type"].as_str().expect("schema property type") {
        "string" => "string".to_owned(),
        "integer" => "number".to_owned(),
        "array" => format!("Array<{}>", typescript_type(&schema["items"])),
        other => panic!("unsupported schema type: {other}"),
    }
}

fn main() {
    let schema = aphrody_a2a::coord::envelope_schema();
    println!("// SPDX-License-Identifier: Apache-2.0");
    println!("// Generated by cargo run -p aphrody-a2a --example export_coord_types. Do not edit.");
    println!(
        "export const COORD_ENVELOPE_KINDS = {} as const;",
        schema["properties"]["kind"]["enum"]
    );
    println!("export type CoordEnvelopeKind = typeof COORD_ENVELOPE_KINDS[number];");
    println!("export interface CoordEnvelope {{");
    let required = schema["required"].as_array().expect("required fields");
    for (name, property) in schema["properties"].as_object().expect("properties") {
        let optional = if required.contains(&Value::String(name.clone())) {
            ""
        } else {
            "?"
        };
        println!("  {name}{optional}: {};", typescript_type(property));
    }
    println!("}}");
}
