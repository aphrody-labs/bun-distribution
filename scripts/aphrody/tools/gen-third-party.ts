#!/usr/bin/env bun
// SPDX-License-Identifier: Apache-2.0
// Generate THIRD-PARTY.md: the monorepo's license manifest. Lists first-party
// crate licenses by bucket, the notable non-Apache first-party components, the
// integrated third-party forks and the upstream reference sources. It does NOT
// relicense anything: per-crate SPDX headers and each upstream's own license
// stay authoritative. Full transitive dependency licenses come from `cargo deny`.
//
//   bun scripts/tools/gen-third-party.ts [--check]
import { Glob } from "bun";
import { resolve } from "node:path";

const ROOT = resolve(import.meta.dir, "../../../").replaceAll("\\", "/");
const OUT = `${ROOT}/THIRD-PARTY.md`;

// First-party crate license fields.
const byLicense = new Map<string, string[]>();
const glob = new Glob("crates/**/Cargo.toml");
for await (const rel of glob.scan({ cwd: ROOT })) {
  const text = await Bun.file(`${ROOT}/${rel}`).text();
  const license = text.match(/^license\s*=\s*"([^"]+)"/m)?.[1];
  const name = text.match(/^name\s*=\s*"([^"]+)"/m)?.[1];
  if (!license || !name) continue;
  const list = byLicense.get(license) ?? [];
  list.push(name);
  byLicense.set(license, list);
}

const upstream = await Bun.file(`${ROOT}/tools/config/upstream-sources.json`).json();
const integrated: any[] = Array.isArray(upstream.integrated) ? upstream.integrated : [];
const reference: any[] = Array.isArray(upstream.reference)
  ? upstream.reference
  : Object.values(upstream.reference ?? {});

const APACHE = new Set(["Apache-2.0", "Apache-2.0 OR MIT", "MIT OR Apache-2.0", "MIT AND Apache-2.0"]);
const nonApache = [...byLicense.entries()].filter(([spdx]) => !APACHE.has(spdx));

const lines: string[] = [];
lines.push("<!-- Generated by scripts/tools/gen-third-party.ts — do not edit by hand. -->");
lines.push("# Third-party licenses and sources");
lines.push("");
lines.push("This monorepo is cross-platform and multi-licensed. First-party code is");
lines.push("**Apache-2.0** (some crates dual `Apache-2.0 OR MIT`). Each crate's own");
lines.push("`license` field and SPDX header is authoritative; this file does not change");
lines.push("any component's license. Third-party forks and upstream inputs keep the");
lines.push("licenses of their authors, listed below so the single-binary build can embed");
lines.push("them with their notices preserved.");
lines.push("");
lines.push("Full transitive dependency licenses (crates.io, npm) are produced on demand:");
lines.push("`cargo deny list` for Rust, `bun pm ls` for Bun packages.");
lines.push("");

lines.push("## First-party crate licenses");
lines.push("");
lines.push("| SPDX | Crates |");
lines.push("| --- | --: |");
for (const [spdx, list] of [...byLicense.entries()].toSorted((a, b) => b[1].length - a[1].length)) {
  lines.push(`| \`${spdx}\` | ${list.length} |`);
}
lines.push("");

lines.push("## Non-Apache first-party components");
lines.push("");
lines.push("These crates are deliberately not Apache-2.0 and keep their own license:");
lines.push("");
for (const [spdx, list] of nonApache.toSorted((a, b) => a[0].localeCompare(b[0]))) {
  lines.push(
    `- **${spdx}**: ${list
      .toSorted()
      .map(c => `\`${c}\``)
      .join(", ")}`,
  );
}
lines.push("");
lines.push("`aphrody-drive` and the `crates/os/kernel/comps/drive` tree derive from Spacedrive");
lines.push("(FSL-1.1-ALv2): source-available, converting to Apache-2.0 two years after");
lines.push("each release. Embedding it in the unified binary is permitted with its");
lines.push("notice preserved; it must not be used to build a competing product.");
lines.push("");

lines.push("## Integrated third-party forks");
lines.push("");
lines.push("Vendored under their capability owner with provenance in");
lines.push("`tools/config/upstream-sources.json`; local patches preserved.");
lines.push("");
lines.push("| Component | Upstream | Version | License | Path |");
lines.push("| --- | --- | --- | --- | --- |");
for (const e of integrated) {
  const ver = e.version ?? e.upstreamTag ?? "";
  lines.push(
    `| ${e.id ?? e.crate ?? ""} | ${e.upstreamUrl ?? ""} | ${ver} | ${e.license ?? ""} | \`${e.integratedPath ?? ""}\` |`,
  );
}
lines.push("");

lines.push("## Upstream reference sources");
lines.push("");
lines.push("Build-recipe inputs tracked for provenance (not vendored source):");
lines.push("");
lines.push("| Source | URL | Ref | Used by |");
lines.push("| --- | --- | --- | --- |");
for (const e of reference) {
  const url = e.url ?? e.upstreamUrl ?? "";
  const ref = e.ref ?? e.upstreamTag ?? e.observedCommit?.slice(0, 12) ?? "";
  const usedBy = e.consumers ?? e.purpose ?? "";
  lines.push(`| ${e.id ?? ""} | ${url} | ${ref} | ${String(usedBy).slice(0, 80)} |`);
}
lines.push("");

const out = lines.join("\n") + "\n";

if (process.argv.includes("--check")) {
  const current = await Bun.file(OUT)
    .text()
    .catch(() => "");
  if (current !== out) {
    console.error("THIRD-PARTY.md is stale; run: bun scripts/tools/gen-third-party.ts");
    process.exit(1);
  }
  console.log("THIRD-PARTY.md up to date.");
} else {
  await Bun.write(OUT, out);
  console.log(
    `Wrote ${OUT} (${byLicense.size} license buckets, ${integrated.length} forks, ${Object.keys(reference).length} upstream refs).`,
  );
}
