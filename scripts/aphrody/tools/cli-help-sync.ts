// Regenerates docs/cli/HELP.md from the package-owned dispatcher and its command help.
import { join } from "node:path";

const root = join(import.meta.dir, "../../../docs/aphrody");
const entry = Bun.resolveSync("@aphrody/yolo-cli/cli", import.meta.dir);
const strip = (s: string) => Bun.stripANSI(s).trimEnd();
const run = async (args: string[]) => {
  const p = Bun.spawn([process.execPath, entry, ...args], {
    windowsHide: true,
    cwd: root,
    stdout: "pipe",
    stderr: "pipe",
    env: { ...process.env, NO_COLOR: "1" },
  });
  const timer = setTimeout(() => p.kill(), 20_000);
  const [o, e] = await Promise.all([
    new Response(p.stdout).text(),
    new Response(p.stderr).text(),
  ]);
  clearTimeout(timer);
  return strip(o || e);
};

// Commands that execute on -h (no usage mode) or are aliases: documented by the top-level help only. `rename` and
// `docs` print the help of the Bun fork's built-in `bun rename|docs`, which an upstream Bun on PATH lacks.
const SKIP = new Set([
  "rename",
  "docs",
  "help",
  "version",
  "uninstall",
  "generate",
  "status",
  "bench",
  "parse",
  "upgrade",
  "ship",
  "doctor",
  "scan",
  "serve",
  "mcp",
  "desktop",
  "tauri",
  "web",
  "py",
  "uv",
  "ops",
  "workspace",
  "workflow",
  "git",
  "ssh",
  "infra",
  "verify",
  "import",
]);
const src = await Bun.file(entry).text();
const commands = [
  ...new Set(
    [...src.matchAll(/^\s{2,4}case "([a-z][a-z0-9-]*)":/gm)].map((m) => m[1]!),
  ),
].filter((c) => !SKIP.has(c));
const out = [
  "# yolo CLI reference",
  "",
  "Generated by `bun scripts/tools/cli-help-sync.ts` from `@aphrody/yolo-cli/cli`. Do not edit by hand.",
  "",
  "## yolo -h",
  "",
  "```",
  await run(["-h"]),
  "```",
];
// desktop-runtime reads `--help`, not `-h`.
const helpFlag = (c: string) => (c === "desktop-runtime" ? "--help" : "-h");
for (const c of commands)
  out.push(
    "",
    `## yolo ${c} -h`,
    "",
    "```",
    await run([c, helpFlag(c)]),
    "```",
  );
const infra = Bun.spawnSync(["aphrody-infra", "--help"], {
  windowsHide: true,
  cwd: root,
})
  .stdout.toString()
  .trimEnd();
if (infra)
  out.push(
    "",
    "## Delegated control plane: infra | workflow | git | ssh | ship | hooks (aphrody-infra --help)",
    "",
    "```",
    infra,
    "```",
  );
await Bun.write(join(root, "docs/cli/HELP.md"), out.join("\n") + "\n");
console.log(`${commands.length} commands: ${commands.join(" ")}`);
