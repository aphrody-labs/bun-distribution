// Regenerates docs/cli/HELP.md from the CLI source: every `case` in apps/yolo/cli/src/index.ts, run with -h.
import { writeFileSync, readFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dir, "../..");
const entry = join(root, "apps/yolo/cli/src/index.ts");
const ESC = String.fromCharCode(27);
const strip = (s: string) => s.replaceAll(new RegExp(`${ESC}\\[[0-9;]*m`, "g"), "").trimEnd();
const run = async (args: string[]) => {
  const p = Bun.spawn(["bun", entry, ...args], {
    cwd: root,
    stdout: "pipe",
    stderr: "pipe",
    env: { ...process.env, NO_COLOR: "1" },
  });
  const timer = setTimeout(() => p.kill(), 20_000);
  const [o, e] = await Promise.all([new Response(p.stdout).text(), new Response(p.stderr).text()]);
  clearTimeout(timer);
  return strip(o || e);
};

// Commands that execute on -h (no usage mode) or are aliases: documented by the top-level help only.
const SKIP = new Set([
  "help",
  "version",
  "uninstall",
  "generate",
  "status",
  "bench",
  "parse",
  "upgrade",
  "ship",
  "doctor",
  "scan",
  "serve",
  "mcp",
  "desktop",
  "tauri",
  "web",
  "py",
  "uv",
  "ops",
  "workspace",
  "workflow",
  "git",
  "ssh",
  "infra",
  "verify",
  "import",
]);
const src = readFileSync(entry, "utf8");
const commands = [
  ...new Set([...src.matchAll(/^\s{2,4}case "([a-z][a-z0-9-]*)":/gm)].map((m) => m[1]!)),
].filter((c) => !SKIP.has(c));
const out = [
  "# yolo CLI reference",
  "",
  "Generated by `bun scripts/tools/cli-help-sync.ts` from `apps/yolo/cli/src/index.ts`. Do not edit by hand.",
  "",
  "## yolo -h",
  "",
  "```",
  await run(["-h"]),
  "```",
];
// desktop-runtime reads `--help`, not `-h`.
const helpFlag = (c: string) => (c === "desktop-runtime" ? "--help" : "-h");
for (const c of commands)
  out.push("", `## yolo ${c} -h`, "", "```", await run([c, helpFlag(c)]), "```");
const infra = Bun.spawnSync(["aphrody-infra", "--help"], { cwd: root }).stdout.toString().trimEnd();
if (infra)
  out.push(
    "",
    "## Delegated control plane: infra | ops | workspace | workflow | git | ssh | ship | hooks (aphrody-infra --help)",
    "",
    "```",
    infra,
    "```",
  );
writeFileSync(join(root, "docs/cli/HELP.md"), out.join("\n") + "\n");
console.log(`${commands.length} commands: ${commands.join(" ")}`);
