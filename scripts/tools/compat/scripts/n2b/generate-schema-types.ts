// Codegen schéma — source de vérité unique : crates/contracts/schema/v2.json
// (the N2B report schema is owned by the Contracts domain of this monorepo).
// Produit :
//   - crates/compat/n2b-types/src/schema.rs       via `cargo typify`
//   - packages/compat/n2b-types/src/index.ts      via `json-schema-to-typescript --unreachableDefinitions`
//
// Les deux fichiers sont commités. La CI échoue si drift (mode --check).
//
// Usage :
//   bun scripts/tools/compat/scripts/n2b/generate-schema-types.ts           # régénère
//   bun scripts/tools/compat/scripts/n2b/generate-schema-types.ts --check   # exit 1 si drift
// (`cargo typify` is a Cargo subcommand: only the integrating agent runs it.)

import { $ } from "bun";
import { existsSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";

// scripts/tools/compat/scripts/n2b -> repository root is five levels up.
const REPO_ROOT = resolve(import.meta.dir, "..", "..", "..", "..", "..");
const SCHEMA = resolve(REPO_ROOT, "crates", "contracts", "schema", "v2.json");
const RUST_OUT = `${REPO_ROOT}/crates/compat/n2b-types/src/schema.rs`;
const TS_OUT = `${REPO_ROOT}/packages/compat/n2b-types/src/index.ts`;

const BANNER_RS = `// @generated — DO NOT EDIT MANUALLY.
// Regenerate with: bun run n2b:codegen
// Source of truth: crates/contracts/schema/v2.json

`;

const BANNER_TS = `// @generated — DO NOT EDIT MANUALLY.
// Regenerate with: bun run n2b:codegen
// Source of truth: crates/contracts/schema/v2.json

`;

const HEADER_TS_REGEX =
	/^\/\* eslint-disable \*\/\n\/\*\*\n \* This file was automatically generated by json-schema-to-typescript\.\n \* DO NOT MODIFY IT BY HAND\. Instead, modify the source JSONSchema file,\n \* and run json-schema-to-typescript to regenerate this file\.\n \*\/\n/;

async function generateRust(): Promise<string> {
	const tmp = join(tmpdir(), `n2b-schema-${process.pid}.rs`);
	const result = await $`cargo typify -o ${tmp} ${SCHEMA}`.quiet();
	if (result.exitCode !== 0) {
		throw new Error(`cargo typify failed: ${result.stderr.toString()}`);
	}
	// Format with the repository rustfmt policy so the committed file is also `cargo fmt --check`
	// clean and `--check` compares like with like.
	const fmt =
		await $`rustfmt --config-path ${join(REPO_ROOT, "rustfmt.toml")} ${tmp}`.quiet().nothrow();
	if (fmt.exitCode !== 0) {
		throw new Error(`rustfmt failed: ${fmt.stderr.toString()}`);
	}
	const body = await Bun.file(tmp).text();
	await Bun.file(tmp).delete();
	return BANNER_RS + body;
}

async function generateTs(): Promise<string> {
	const result =
		await $`bunx --bun json-schema-to-typescript --unreachableDefinitions ${SCHEMA}`.quiet();
	if (result.exitCode !== 0) {
		throw new Error(
			`json-schema-to-typescript failed: ${result.stderr.toString()}`,
		);
	}
	const out = result.stdout.toString();
	if (!HEADER_TS_REGEX.test(out)) {
		throw new Error(
			"json-schema-to-typescript output header changed; update HEADER_TS_REGEX",
		);
	}
	return BANNER_TS + out.replace(HEADER_TS_REGEX, "").replace(/^\n+/, "");
}

async function main(): Promise<void> {
	if (!existsSync(SCHEMA)) {
		console.error(`schema not found: ${SCHEMA}`);
		process.exit(1);
	}

	const check = process.argv.includes("--check");
	const [rust, ts] = await Promise.all([generateRust(), generateTs()]);

	if (check) {
		const [rustCommitted, tsCommitted] = await Promise.all([
			Bun.file(RUST_OUT).text(),
			Bun.file(TS_OUT).text(),
		]);
		let drift = false;
		if (rust !== rustCommitted) {
			console.error(`drift: ${RUST_OUT}`);
			drift = true;
		}
		if (ts !== tsCommitted) {
			console.error(`drift: ${TS_OUT}`);
			drift = true;
		}
		if (drift) {
			console.error(
				"\nRun `bun run n2b:codegen` and commit the regenerated files.",
			);
			process.exit(1);
		}
		console.log("n2b:codegen:check OK — no drift");
		return;
	}

	await Promise.all([Bun.write(RUST_OUT, rust), Bun.write(TS_OUT, ts)]);
	console.log(`wrote ${RUST_OUT}`);
	console.log(`wrote ${TS_OUT}`);
}

main().catch((err) => {
	console.error(err);
	process.exit(1);
});
