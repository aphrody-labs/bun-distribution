#!/usr/bin/env bun
/**
 * create-mega-data-tables.ts
 *
 * Crée les tables des 5 nouveaux piliers majeurs dans PostgreSQL (schéma `bot`) et SQLite (apps/bot/data/bot.db) :
 * 1. bot.db_battles
 * 2. bot.db_timeline_events
 * 3. bot.db_power_levels
 * 4. bot.db_items
 * 5. bot.db_dragons
 * 6. bot.db_wishes
 */

import { existsSync, readFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { Database } from "bun:sqlite";
import postgres from "postgres";

function getPgUrl(): string | null {
  if (process.env.DATABASE_URL) return process.env.DATABASE_URL;
  const envPath = process.env.SHENRON_PG_ENV || join(homedir(), ".shenron-neon.env");
  if (existsSync(envPath)) {
    try {
      const content = readFileSync(envPath, "utf8");
      const lines = content.split("\n").filter((l) => l.startsWith("DATABASE_URL="));
      const last = lines.at(-1);
      if (last) {
        return last.slice("DATABASE_URL=".length).trim().replace(/^["']|["']$/g, "");
      }
    } catch {}
  }
  return null;
}

const sqlitePath = join(import.meta.dir, "../../apps/bot/data/bot.db");

async function main() {
  console.log("🐉 Création des tables mega-data dans PostgreSQL et SQLite...");

  // 1. PostgreSQL
  const pgUrl = getPgUrl();
  if (pgUrl) {
    const sql = postgres(pgUrl, { max: 2 });
    console.log("-> Connexion PostgreSQL établie...");

    await sql`
      CREATE TABLE IF NOT EXISTS bot.db_battles (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        slug text NOT NULL UNIQUE,
        title text NOT NULL,
        title_ja text,
        saga_id bigint,
        arc_id bigint,
        series text NOT NULL,
        combatants jsonb NOT NULL DEFAULT '[]'::jsonb,
        winner_id bigint,
        winner_name text,
        location text,
        manga_volume_start bigint,
        manga_volume_end bigint,
        manga_chapter_start bigint,
        manga_chapter_end bigint,
        episode_start bigint,
        episode_end bigint,
        techniques_used jsonb DEFAULT '[]'::jsonb,
        climax_summary text,
        canon boolean NOT NULL DEFAULT true,
        impact_level bigint DEFAULT 3,
        article text,
        article_sources jsonb,
        article_updated_at bigint,
        visible boolean NOT NULL DEFAULT true
      );
    `;

    await sql`
      CREATE TABLE IF NOT EXISTS bot.db_timeline_events (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        age_year bigint NOT NULL,
        age_month bigint,
        age_day bigint,
        era text NOT NULL,
        title text NOT NULL,
        title_ja text,
        description text NOT NULL,
        characters_involved jsonb DEFAULT '[]'::jsonb,
        source_ref text,
        canon boolean NOT NULL DEFAULT true,
        order_idx bigint NOT NULL DEFAULT 0,
        visible boolean NOT NULL DEFAULT true
      );
    `;

    await sql`
      CREATE TABLE IF NOT EXISTS bot.db_power_levels (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        character_id bigint,
        character_name text NOT NULL,
        form text,
        saga_id bigint,
        saga_name text,
        battle_power bigint,
        battle_power_display text NOT NULL,
        scouter_device text,
        source_kind text NOT NULL,
        source_page text,
        canon boolean NOT NULL DEFAULT true,
        notes text,
        visible boolean NOT NULL DEFAULT true
      );
    `;

    await sql`
      CREATE TABLE IF NOT EXISTS bot.db_items (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        slug text NOT NULL UNIQUE,
        name text NOT NULL,
        name_ja text,
        name_romaji text,
        category text NOT NULL,
        creator text,
        description text NOT NULL,
        debut_chapter text,
        debut_episode text,
        image text,
        article text,
        article_sources jsonb,
        article_updated_at bigint,
        visible boolean NOT NULL DEFAULT true
      );
    `;

    await sql`
      CREATE TABLE IF NOT EXISTS bot.db_dragons (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        slug text NOT NULL UNIQUE,
        name text NOT NULL,
        name_ja text,
        creator text,
        planet_realm text,
        balls_count bigint NOT NULL DEFAULT 7,
        balls_diameter text,
        summon_phrase text,
        summon_phrase_ja text,
        wishes_count bigint NOT NULL DEFAULT 1,
        cooldown text,
        rules text,
        image text,
        article text,
        article_sources jsonb,
        article_updated_at bigint,
        visible boolean NOT NULL DEFAULT true
      );
    `;

    await sql`
      CREATE TABLE IF NOT EXISTS bot.db_wishes (
        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        dragon_id bigint NOT NULL,
        dragon_name text NOT NULL,
        wish_number_in_summon bigint NOT NULL DEFAULT 1,
        whisperer text NOT NULL,
        saga text NOT NULL,
        manga_chapter bigint,
        episode_number bigint,
        wish_text text NOT NULL,
        granted boolean NOT NULL DEFAULT true,
        canon boolean NOT NULL DEFAULT true,
        visible boolean NOT NULL DEFAULT true
      );
    `;

    // Indexation PostgreSQL
    await sql`CREATE INDEX IF NOT EXISTS idx_battles_slug ON bot.db_battles(slug);`;
    await sql`CREATE INDEX IF NOT EXISTS idx_battles_saga ON bot.db_battles(saga_id);`;
    await sql`CREATE INDEX IF NOT EXISTS idx_timeline_age ON bot.db_timeline_events(age_year, order_idx);`;
    await sql`CREATE INDEX IF NOT EXISTS idx_timeline_era ON bot.db_timeline_events(era);`;
    await sql`CREATE INDEX IF NOT EXISTS idx_power_levels_char ON bot.db_power_levels(character_id);`;
    await sql`CREATE INDEX IF NOT EXISTS idx_items_slug ON bot.db_items(slug);`;
    await sql`CREATE INDEX IF NOT EXISTS idx_items_cat ON bot.db_items(category);`;
    await sql`CREATE INDEX IF NOT EXISTS idx_dragons_slug ON bot.db_dragons(slug);`;
    await sql`CREATE INDEX IF NOT EXISTS idx_wishes_dragon ON bot.db_wishes(dragon_id);`;

    console.log("✅ Tables PostgreSQL bot.db_* créées et indexées.");
    await sql.end();
  } else {
    console.warn("⚠️ Aucune URL PostgreSQL trouvée.");
  }

  // 2. SQLite (Miroir local bot)
  if (existsSync(sqlitePath)) {
    const sdb = new Database(sqlitePath);
    sdb.run(`
      CREATE TABLE IF NOT EXISTS db_battles (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        slug TEXT NOT NULL UNIQUE,
        title TEXT NOT NULL,
        title_ja TEXT,
        saga_id INTEGER,
        arc_id INTEGER,
        series TEXT NOT NULL,
        combatants TEXT NOT NULL DEFAULT '[]',
        winner_id INTEGER,
        winner_name TEXT,
        location TEXT,
        manga_volume_start INTEGER,
        manga_volume_end INTEGER,
        manga_chapter_start INTEGER,
        manga_chapter_end INTEGER,
        episode_start INTEGER,
        episode_end INTEGER,
        techniques_used TEXT DEFAULT '[]',
        climax_summary TEXT,
        canon INTEGER NOT NULL DEFAULT 1,
        impact_level INTEGER DEFAULT 3,
        article TEXT,
        article_sources TEXT,
        article_updated_at INTEGER,
        visible INTEGER NOT NULL DEFAULT 1
      );
    `);

    sdb.run(`
      CREATE TABLE IF NOT EXISTS db_timeline_events (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        age_year INTEGER NOT NULL,
        age_month INTEGER,
        age_day INTEGER,
        era TEXT NOT NULL,
        title TEXT NOT NULL,
        title_ja TEXT,
        description TEXT NOT NULL,
        characters_involved TEXT DEFAULT '[]',
        source_ref TEXT,
        canon INTEGER NOT NULL DEFAULT 1,
        order_idx INTEGER NOT NULL DEFAULT 0,
        visible INTEGER NOT NULL DEFAULT 1
      );
    `);

    sdb.run(`
      CREATE TABLE IF NOT EXISTS db_power_levels (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        character_id INTEGER,
        character_name TEXT NOT NULL,
        form TEXT,
        saga_id INTEGER,
        saga_name TEXT,
        battle_power INTEGER,
        battle_power_display TEXT NOT NULL,
        scouter_device TEXT,
        source_kind TEXT NOT NULL,
        source_page TEXT,
        canon INTEGER NOT NULL DEFAULT 1,
        notes TEXT,
        visible INTEGER NOT NULL DEFAULT 1
      );
    `);

    sdb.run(`
      CREATE TABLE IF NOT EXISTS db_items (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        slug TEXT NOT NULL UNIQUE,
        name TEXT NOT NULL,
        name_ja TEXT,
        name_romaji TEXT,
        category TEXT NOT NULL,
        creator TEXT,
        description TEXT NOT NULL,
        debut_chapter TEXT,
        debut_episode TEXT,
        image TEXT,
        article TEXT,
        article_sources TEXT,
        article_updated_at INTEGER,
        visible INTEGER NOT NULL DEFAULT 1
      );
    `);

    sdb.run(`
      CREATE TABLE IF NOT EXISTS db_dragons (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        slug TEXT NOT NULL UNIQUE,
        name TEXT NOT NULL,
        name_ja TEXT,
        creator TEXT,
        planet_realm TEXT,
        balls_count INTEGER NOT NULL DEFAULT 7,
        balls_diameter TEXT,
        summon_phrase TEXT,
        summon_phrase_ja TEXT,
        wishes_count INTEGER NOT NULL DEFAULT 1,
        cooldown TEXT,
        rules TEXT,
        image TEXT,
        article TEXT,
        article_sources TEXT,
        article_updated_at INTEGER,
        visible INTEGER NOT NULL DEFAULT 1
      );
    `);

    sdb.run(`
      CREATE TABLE IF NOT EXISTS db_wishes (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        dragon_id INTEGER NOT NULL,
        dragon_name TEXT NOT NULL,
        wish_number_in_summon INTEGER NOT NULL DEFAULT 1,
        whisperer TEXT NOT NULL,
        saga TEXT NOT NULL,
        manga_chapter INTEGER,
        episode_number INTEGER,
        wish_text TEXT NOT NULL,
        granted INTEGER NOT NULL DEFAULT 1,
        canon INTEGER NOT NULL DEFAULT 1,
        visible INTEGER NOT NULL DEFAULT 1
      );
    `);

    sdb.close();
    console.log("✅ Tables SQLite miroir créées avec succès.");
  }

  console.log("🎉 Initialisation réussie des 6 tables piliers !");
}

main().catch(console.error);
