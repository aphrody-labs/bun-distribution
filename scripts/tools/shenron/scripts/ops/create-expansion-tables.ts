#!/usr/bin/env bun
/**
 * create-expansion-tables.ts — Création des 4 tables de souveraineté encyclopédique
 * Lieux, Tournois, Voix/Seiyū, Musiques & Bandes Originales.
 */
import { existsSync, readFileSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { Database } from "bun:sqlite";
import postgres from "postgres";

function getPgUrl(): string | null {
  if (process.env.DATABASE_URL) return process.env.DATABASE_URL;
  const envPath = process.env.SHENRON_PG_ENV || join(homedir(), ".shenron-neon.env");
  if (existsSync(envPath)) {
    try {
      const content = readFileSync(envPath, "utf8");
      const lines = content.split("\n").filter((l) => l.startsWith("DATABASE_URL="));
      const last = lines.at(-1);
      if (last) {
        return last.slice("DATABASE_URL=".length).trim().replace(/^["\x27]|["\x27]$/g, "");
      }
    } catch {}
  }
  return null;
}

const sqlitePath = join(import.meta.dir, "../../apps/bot/data/bot.db");

async function main() {
  const pgUrl = getPgUrl();
  if (pgUrl) {
    console.log("Connexion à PostgreSQL (Neon)...");
    const sql = postgres(pgUrl);

    console.log("Création de bot.db_locations...");
    await sql`
      CREATE TABLE IF NOT EXISTS bot.db_locations (
        id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        slug text UNIQUE NOT NULL,
        name text NOT NULL,
        name_ja text,
        name_romaji text,
        realm_type text NOT NULL,
        planet text,
        description text NOT NULL,
        debut_chapter text,
        debut_episode text,
        key_events jsonb,
        image text,
        article text,
        article_sources text,
        visible boolean DEFAULT true NOT NULL
      )
    `;

    console.log("Création de bot.db_tournaments...");
    await sql`
      CREATE TABLE IF NOT EXISTS bot.db_tournaments (
        id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        slug text UNIQUE NOT NULL,
        name text NOT NULL,
        name_ja text,
        tournament_type text NOT NULL,
        saga text NOT NULL,
        location text,
        winner_name text,
        runner_up_name text,
        rules_summary text NOT NULL,
        participants_count int,
        notable_matches jsonb,
        canon boolean DEFAULT true NOT NULL,
        article text,
        article_sources text,
        visible boolean DEFAULT true NOT NULL
      )
    `;

    console.log("Création de bot.db_voice_actors...");
    await sql`
      CREATE TABLE IF NOT EXISTS bot.db_voice_actors (
        id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        slug text UNIQUE NOT NULL,
        name text NOT NULL,
        name_ja text,
        nationality text NOT NULL,
        birth_date text,
        roles jsonb NOT NULL,
        biography text NOT NULL,
        image text,
        article text,
        article_sources text,
        visible boolean DEFAULT true NOT NULL
      )
    `;

    console.log("Création de bot.db_soundtracks...");
    await sql`
      CREATE TABLE IF NOT EXISTS bot.db_soundtracks (
        id int GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        slug text UNIQUE NOT NULL,
        title text NOT NULL,
        title_ja text,
        title_romaji text,
        track_type text NOT NULL,
        series text NOT NULL,
        artist text NOT NULL,
        composer text,
        lyricist text,
        episodes_range text,
        release_year int,
        description text NOT NULL,
        article text,
        article_sources text,
        visible boolean DEFAULT true NOT NULL
      )
    `;

    console.log("PostgreSQL : tables créées avec succès.");
    await sql.end();
  }

  // SQLite réplica local
  if (existsSync(sqlitePath)) {
    console.log("Mise à jour du schéma SQLite local (bot.db)...");
    const sdb = new Database(sqlitePath);
    sdb.exec("PRAGMA busy_timeout = 5000;");

    sdb.exec(`
      CREATE TABLE IF NOT EXISTS db_locations (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        slug TEXT UNIQUE NOT NULL,
        name TEXT NOT NULL,
        name_ja TEXT,
        name_romaji TEXT,
        realm_type TEXT NOT NULL,
        planet TEXT,
        description TEXT NOT NULL,
        debut_chapter TEXT,
        debut_episode TEXT,
        key_events TEXT,
        image TEXT,
        article TEXT,
        article_sources TEXT,
        visible INTEGER DEFAULT 1 NOT NULL
      );

      CREATE TABLE IF NOT EXISTS db_tournaments (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        slug TEXT UNIQUE NOT NULL,
        name TEXT NOT NULL,
        name_ja TEXT,
        tournament_type TEXT NOT NULL,
        saga TEXT NOT NULL,
        location TEXT,
        winner_name TEXT,
        runner_up_name TEXT,
        rules_summary TEXT NOT NULL,
        participants_count INTEGER,
        notable_matches TEXT,
        canon INTEGER DEFAULT 1 NOT NULL,
        article TEXT,
        article_sources TEXT,
        visible INTEGER DEFAULT 1 NOT NULL
      );

      CREATE TABLE IF NOT EXISTS db_voice_actors (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        slug TEXT UNIQUE NOT NULL,
        name TEXT NOT NULL,
        name_ja TEXT,
        nationality TEXT NOT NULL,
        birth_date TEXT,
        roles TEXT NOT NULL,
        biography TEXT NOT NULL,
        image TEXT,
        article TEXT,
        article_sources TEXT,
        visible INTEGER DEFAULT 1 NOT NULL
      );

      CREATE TABLE IF NOT EXISTS db_soundtracks (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        slug TEXT UNIQUE NOT NULL,
        title TEXT NOT NULL,
        title_ja TEXT,
        title_romaji TEXT,
        track_type TEXT NOT NULL,
        series TEXT NOT NULL,
        artist TEXT NOT NULL,
        composer TEXT,
        lyricist TEXT,
        episodes_range TEXT,
        release_year INTEGER,
        description TEXT NOT NULL,
        article TEXT,
        article_sources TEXT,
        visible INTEGER DEFAULT 1 NOT NULL
      );
    `);
    sdb.close();
    console.log("SQLite : tables créées avec succès.");
  }
}

main().catch(console.error);
