import { join, resolve } from "node:path";
import { mkdir } from "node:fs/promises";
import { runProcess } from "@aphrody/bun-workspace/process";

const root = resolve(import.meta.dir, "..");
const publicSource =
  "https://source.aphrody.app/aphrody-dev/bun-distribution.git";
const hostKey =
  "AAAAC3NzaC1lZDI1NTE5AAAAILtKSA2rakkVJJdmOWdK2JRt4VpeXP+sUsO9k491hLm1";
const fingerprint = "SHA256:M48ORSUT/TU1sYsWPunaXwQliH0bUVRviGx7m4gWOAs";
const deadline = Date.now() + 30000;

async function inspect(args: string[], optional = false): Promise<string> {
  const remaining = deadline - Date.now();
  if (remaining < 1)
    throw new Error("Forge transport qualification deadline exceeded.");
  const result = await runProcess(args, root, {
    timeoutMs: Math.min(15000, remaining),
    maxOutputBytes: 1048576,
  });
  if (result.code && !optional)
    throw new Error("Forge transport inspection failed.");
  return result.code ? "" : result.stdout.trim();
}

const action = Bun.argv[2] ?? "plan";
if (action !== "plan" && action !== "configure")
  throw new Error("Use forge-transport.ts plan | configure.");
const windows = process.platform === "win32";
const ssh = windows
  ? join(Bun.env.ProgramFiles ?? "C:/Program Files", "OpenSSH/ssh.exe")
  : "/usr/bin/ssh";
if (!(await Bun.file(ssh).exists()))
  throw new Error("Native OpenSSH client is unavailable.");
const sshPath = ssh.replaceAll("\\", "/");
const effective = await inspect([ssh, "-G", "bun-forge"]);
const fields = new Map(
  effective
    .split(/\r?\n/)
    .map((line) => [line.split(" ", 1)[0]!, line.slice(line.indexOf(" ") + 1)]),
);
if (
  fields.get("hostname") !== "127.0.0.1" ||
  fields.get("port") !== "29022" ||
  fields.get("user") !== "git"
)
  throw new Error(
    "The Infra-owned bun-forge alias must target git@127.0.0.1:29022.",
  );
const knownHosts = fields.get("userknownhostsfile");
if (!knownHosts || !(await Bun.file(knownHosts).exists()))
  throw new Error("Protected owner known_hosts is unavailable.");
const keygen = Bun.which(windows ? "ssh-keygen.exe" : "ssh-keygen");
if (!keygen) throw new Error("Native SSH host key inspection is unavailable.");
const known = await inspect([keygen, "-F", "bun-forge", "-f", knownHosts]);
if (
  !known
    .split(/\r?\n/)
    .some(
      (line) =>
        line.split(/\s+/)[1] === "ssh-ed25519" &&
        line.split(/\s+/)[2] === hostKey,
    )
)
  throw new Error(
    "The Infra forge ED25519 host key does not match the pinned source.",
  );
const directory = resolve(
  root,
  await inspect(["git", "rev-parse", "--git-common-dir"]),
  "aphrody-forge",
);
const configPath = join(directory, "ssh-config").replaceAll("\\", "/");
const ownerConfig = join(
  Bun.env.USERPROFILE ?? Bun.env.HOME ?? "",
  ".ssh/config",
).replaceAll("\\", "/");
if (!(await Bun.file(ownerConfig).exists()))
  throw new Error("Infra-owned SSH configuration is unavailable.");
for (const value of [sshPath, knownHosts, configPath, ownerConfig])
  if (/["'`$;&|<>\r\n]/.test(value))
    throw new Error("Unsupported SSH configuration path.");
const proxy = `"${sshPath}" -o BatchMode=yes -o StrictHostKeyChecking=yes -o ConnectTimeout=15 -W %h:%p vps`;
const content = [
  "# Generated by scripts/forge-transport.ts; no credentials are stored here.",
  "Host bun-forge",
  "    HostName 127.0.0.1",
  "    Port 29022",
  "    User git",
  "    HostKeyAlias bun-forge",
  "    BatchMode yes",
  "    IdentitiesOnly yes",
  "    ConnectTimeout 15",
  "    StrictHostKeyChecking yes",
  "    HostKeyAlgorithms ssh-ed25519",
  `    UserKnownHostsFile "${knownHosts}"`,
  ...(windows ? [`    ProxyCommand ${proxy}`, "    ProxyJump none"] : []),
  "Host *",
  `    Include "${ownerConfig}"`,
  "",
].join("\n");
const sshCommand = `"${sshPath}" -F "${configPath}"`;
const existing = await inspect(
  ["git", "config", "--local", "--get", "core.sshCommand"],
  true,
);
if (existing && existing !== sshCommand)
  throw new Error("Another repository SSH transport is already configured.");
if (action === "configure") {
  if (Bun.env.GIT_SSH_COMMAND || Bun.env.GIT_SSH)
    throw new Error(
      "Remove environment SSH overrides before qualifying repository-local transport.",
    );
  const revision = await inspect(["git", "rev-parse", "HEAD"]);
  const committedScript = await inspect([
    "git",
    "rev-parse",
    `${revision}:scripts/forge-transport.ts`,
  ]);
  if (
    committedScript !==
    (await inspect([
      "git",
      "hash-object",
      "--path=scripts/forge-transport.ts",
      import.meta.path,
    ]))
  )
    throw new Error("Commit the transport owner before configuring it.");
  const crateLink = await inspect([
    "git",
    "ls-tree",
    revision,
    "--",
    "crates/craft-fonts",
  ]);
  const expectedCrate =
    /^160000 commit ([a-f0-9]{40})\tcrates\/craft-fonts$/.exec(crateLink)?.[1];
  if (!expectedCrate)
    throw new Error("The committed private crate gitlink is unavailable.");
  // The probe uses the owner's existing key through its SSH config, without copying it.
  const probeCommand = windows
    ? `"${sshPath}" -o 'ProxyCommand="${sshPath}" -o BatchMode=yes -o StrictHostKeyChecking=yes -o ConnectTimeout=15 -W %h:%p vps' -o ProxyJump=none -o BatchMode=yes -o StrictHostKeyChecking=yes -o HostKeyAlgorithms=ssh-ed25519 -o ConnectTimeout=15`
    : `"${sshPath}" -o BatchMode=yes -o StrictHostKeyChecking=yes -o HostKeyAlgorithms=ssh-ed25519 -o ConnectTimeout=15`;
  const privateRefs = await inspect([
    "git",
    "-c",
    `core.sshCommand=${probeCommand}`,
    "ls-remote",
    "bun-forge:aphrody-dev/bun-crate-craft-fonts.git",
    "refs/heads/os",
  ]);
  if (
    !/^[a-f0-9]{40}\s+refs\/heads\/os$/.test(privateRefs) ||
    privateRefs.split(/\s+/)[0] !== expectedCrate
  )
    throw new Error(
      "The owner forge identity cannot read the committed private crate revision.",
    );
  if ((await inspect(["git", "rev-parse", "HEAD"])) !== revision)
    throw new Error("Source revision changed during transport qualification.");
  if (await Bun.file(configPath).exists()) {
    const previous = await Bun.file(configPath).text();
    const knownPrevious = windows
      ? content.replace(
          `    ProxyCommand ${proxy}\n    ProxyJump none`,
          `    ProxyJump none\n    ProxyCommand ${proxy}`,
        )
      : content;
    if (previous !== content && previous !== knownPrevious)
      throw new Error(
        "Another generated SSH configuration already owns this path.",
      );
  }
  await mkdir(directory, { recursive: true });
  await Bun.write(configPath, content);
  await inspect(["git", "config", "--local", "core.sshCommand", sshCommand]);
  const routed = await inspect([ssh, "-G", "-F", configPath, "bun-forge"]);
  const routedFields = new Map(
    routed
      .split(/\r?\n/)
      .map((line) => [
        line.split(" ", 1)[0]!,
        line.slice(line.indexOf(" ") + 1),
      ]),
  );
  if (
    routedFields.get("hostname") !== "127.0.0.1" ||
    routedFields.get("port") !== "29022" ||
    routedFields.get("user") !== "git" ||
    (windows && routedFields.get("proxycommand") !== proxy)
  )
    throw new Error("Generated repository SSH routing failed qualification.");
  const configuredRefs = await inspect([
    "git",
    "ls-remote",
    "bun-forge:aphrody-dev/bun-crate-craft-fonts.git",
    "refs/heads/os",
  ]);
  if (
    !/^[a-f0-9]{40}\s+refs\/heads\/os$/.test(configuredRefs) ||
    configuredRefs.split(/\s+/)[0] !== expectedCrate
  )
    throw new Error(
      "Repository-local SSH transport cannot read the committed private crate revision.",
    );
  if ((await inspect(["git", "rev-parse", "HEAD"])) !== revision)
    throw new Error("Source revision changed after transport configuration.");
}
console.log(
  JSON.stringify({
    action,
    configured: action === "configure",
    fingerprint,
    publicSource,
    alias: "bun-forge",
    globalConfigChanged: false,
  }),
);
