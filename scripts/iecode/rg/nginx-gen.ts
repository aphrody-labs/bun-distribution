/**
 * Render the RG production gateway (`rg.conf`) from `$YOLO_ROOT/config/host/rg/nginx-routes.json`.
 * Hosts, aliases and loopback upstreams come from the route catalog; the per-host policy blocks
 * (CDN retirements, redirects, WebSocket upgrades) live here once, with shared partials for the
 * TLS and proxy boilerplate.
 *
 *   bun scripts/iecode/rg/nginx-gen.ts [--out FILE]   write (default: stdout)
 *   bun scripts/iecode/rg/nginx-gen.ts --check FILE   exit 1 when FILE differs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

interface Route {
  host: string;
  service: string;
  upstream: string;
  aliases?: string[];
  status?: string;
}
interface Catalog {
  routes: Route[];
  internalGateway: string;
}

const catalog = JSON.parse(
  readFileSync(
    join(
      process.env.YOLO_ROOT ?? join(process.env.HOME ?? process.env.USERPROFILE ?? "", "yolo"),
      "config/host/rg/nginx-routes.json",
    ),
    "utf8",
  ),
) as Catalog;
const live = catalog.routes.filter(route => route.status !== "retired" && route.host.endsWith("rosegriffon.fr"));
const up = (host: string) => {
  const route = live.find(r => r.host === host);
  if (!route) throw new Error(`no live route for ${host}`);
  return `http://${route.upstream}`;
};
const web = up("rosegriffon.fr");
const api = up("api.rosegriffon.fr");
const achillea = up("achillea.rosegriffon.fr");
const ranked = up("ranked.rosegriffon.fr");

const names = (route: Route) => [route.host, ...(route.aliases ?? [])].join(" ");
const tls = (host: string) => `    listen 443 ssl;
    server_name ${names(live.find(r => r.host === host)!)};
    ssl_certificate /etc/letsencrypt/live/${host}/fullchain.pem;
    ssl_certificate_key /etc/letsencrypt/live/${host}/privkey.pem;`;
const proxy = (target: string, indent = "        ", extra: string[] = []) =>
  [
    `proxy_pass ${target};`,
    "proxy_http_version 1.1;",
    "proxy_set_header Host $host;",
    "proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;",
    "proxy_set_header X-Forwarded-Proto https;",
    ...extra,
  ]
    .map(line => `${indent}${line}`)
    .join("\n");
const upgrade = (target: string) =>
  [
    `proxy_pass ${target};`,
    "proxy_http_version 1.1;",
    "proxy_set_header Upgrade $http_upgrade;",
    'proxy_set_header Connection "upgrade";',
    "proxy_set_header Host $host;",
    "proxy_read_timeout 3600s;",
  ]
    .map(line => `        ${line}`)
    .join("\n");
const supabase = (indent = "    ") =>
  [
    `${indent}location ^~ /storage/v1/ { proxy_pass ${api}; }`,
    `${indent}location ^~ /realtime/v1/ {`,
    `${indent}    proxy_pass ${api};`,
    `${indent}    proxy_buffering off;`,
    `${indent}    proxy_read_timeout 3600s;`,
    `${indent}}`,
  ].join("\n");
const gone = (comment: string, matcher: string) =>
  `    ${comment}\n    location ${matcher} {\n        return 410;\n    }`;

const wikiPaths =
  "chara|skill|item|aura|passive|tactic|equipe|quete|stade|succes|niveau|drops|invocation|entraineur|capsule|gallery|textures|sons|videos|modeles|mode|keshin|tools|save|demo|cross|patch-notes|vroid|avatar";
const nieTexture =
  "cfg|typed|tex|tex-info|audio|audio-info|video|lip|menu-render|model-full|model-chr|model-edit|model-avatar|model-map|avatar|icons|ui";

export function render(): string {
  const all = live.flatMap(route => names(route).split(" "));
  const redirectNames = `${all.slice(0, 6).join(" ")}\n                ${all.slice(6).join(" ")}`;
  return `# RG production gateway. The service catalog owns hosts and loopback ports.
# TLS certificates are provisioned on the VPS; no credentials live in this file.
# Generated by scripts/iecode/rg/nginx-gen.ts from yolo config/host/rg/nginx-routes.json; edit those, not this file.

# One host-aware audience stream for the unified RG gateway. The older split
# vhosts used 00-rg-stats.conf; this release-managed config must define it
# itself because only rg.conf is installed during atomic deployment.
log_format rg_stats escape=json
    '$time_iso8601\\t$host\\t$request_method\\t$uri\\t$status\\t$body_bytes_sent\\t'
    '$request_time\\t$upstream_response_time\\t$upstream_cache_status\\t'
    '$http_referer\\t$http_user_agent\\t$remote_addr';
access_log /var/log/nginx/rg-stats.log rg_stats buffer=32k flush=5s;

server {
    listen 80;
    server_name ${redirectNames};
    location ^~ /.well-known/acme-challenge/ { root /var/www/html; }
    location / { return 301 https://$host$request_uri; }
}

server {
    listen ${catalog.internalGateway};
    server_name _;
    location = /health { return 200 'ok'; }
    location ^~ /storage/v1/ { proxy_pass ${api}; }
    location ^~ /realtime/v1/ {
        proxy_pass ${api};
        proxy_buffering off;
        proxy_read_timeout 3600s;
    }
}

server {
${tls("rosegriffon.fr")}
    client_max_body_size 512m;
${supabase()}
    location ~ ^/llms?(-full)?\\.(txt|md|html)$ {
        root /srv/rg/shared/cron/seo;
        try_files $uri @rg_website;
    }
    location @rg_website {
        proxy_pass ${web};
        proxy_set_header Host $host;
    }
    location / {
${proxy(web, "        ", ["proxy_read_timeout 120s;"])}
    }
}

server {
${tls("api.rosegriffon.fr")}
    location / {
${proxy(api)}
    }
}

server {
${tls("cdn.rosegriffon.fr")}
    client_max_body_size 512m;
    # Assets statiques publiés sur disque (rg-cron \`cdn\` pour /static/rg/public,
    # pipeline Azalée pour /static/azalee) : servis par nginx, jamais par rg-cdn.
    location ^~ /static/ {
        root /var/www/cdn;
        gzip_static on;
        brotli_static on;
        expires 30d;
        add_header Cache-Control "public" always;
        add_header Access-Control-Allow-Origin "*" always;
        add_header X-Content-Type-Options "nosniff" always;
        try_files $uri =404;
    }
    # Content-addressed uploads that rg-cdn (/upload) stores in /var/www/cdn/images.
    location ~* "^/[a-f0-9]{16}\\.(png|jpg|jpeg|webp|gif|svg)$" {
        root /var/www/cdn/images;
        expires 365d;
        add_header Access-Control-Allow-Origin "*" always;
        add_header Cross-Origin-Resource-Policy "cross-origin" always;
        add_header X-Content-Type-Options "nosniff" always;
        try_files $uri @rg_cdn;
    }
    location @rg_cdn {
${proxy(api)}
    }
    # Inazuma Eleven Cross assets extracted to disk.
    location ^~ /cross/ {
        alias /var/www/cdn/cross/;
        expires 30d;
        add_header Access-Control-Allow-Origin "*" always;
        add_header Cross-Origin-Resource-Policy "cross-origin" always;
        try_files $uri =404;
    }
    location = /robots.txt {
        default_type text/plain;
        return 200 "User-agent: *\\nDisallow: /upload\\nAllow: /\\n";
    }
${gone("# NIE and the IECode game asset origin were retired on 2026-09-25.", "^~ /dx11/")}
${gone("# NIE decoded texture/container API is unavailable until the service is redeployed.", "^~ /g4tx/")}
    # Raw/source game bytes are never public; NIE is retired and these stay closed.
    location ~ ^/(raw|depot)(/|$) {
        return 404;
    }
${gone("# VFS tree API is unavailable until NIE is redeployed.", "~ ^/vfs(/|$)")}
${gone("# Converted game exports are unavailable until NIE is redeployed.", "~ ^/export/")}
${gone("# Decoded game data, models and menu renders are unavailable until NIE returns.", `~ ^/(${nieTexture})/`)}
${gone("# Assembled 3D models and previews are unavailable until NIE returns.", "~ ^/model/[A-Za-z0-9_-]+/[A-Za-z0-9_.-]+\\.(glb|png)$")}
    location ~ ^/(menu-tree|story-scene)(/|\\.json$|$) {
        return 410;
    }
    location / {
${proxy(api)}
    }
}

server {
${tls("achillea.rosegriffon.fr")}
${supabase()}
    location = /health/check { proxy_pass ${achillea}; }
    location ^~ /api/ {
${proxy(achillea)}
    }
    location / { return 301 https://rosegriffon.fr/achillea; }
}

server {
${tls("ranked.rosegriffon.fr")}
    location = /health/check { proxy_pass ${achillea}; }
    # The ranked service is an API/WebSocket backend; its UI lives on the website.
    # Plain page loads of the root redirect there; WebSocket upgrades still pass.
    location = / {
        if ($http_upgrade = "") { return 301 https://rosegriffon.fr/achillea/ranked; }
${upgrade(ranked)}
    }
    location / {
${upgrade(ranked)}
    }
}

# Legacy Azalee host: public storage objects are still referenced by stored
# content and by the Next image optimizer; the site itself moved to rosegriffon.fr.
server {
${tls("azalee.rosegriffon.fr")}
    location ^~ /storage/v1/ {
${proxy(api)}
    }
    location ^~ /dashboard {
        rewrite ^/dashboard/?$ https://rosegriffon.fr/admin permanent;
        rewrite ^/dashboard/(.*)$ https://rosegriffon.fr/admin/$1 permanent;
    }
    location ~ ^/(${wikiPaths})(/|$) {
        return 301 https://rosegriffon.fr/wiki$request_uri;
    }
    location = / { return 301 https://rosegriffon.fr/wiki; }
    location / { return 301 https://rosegriffon.fr$request_uri; }
}
`;
}

if (import.meta.main) {
  const args = process.argv.slice(2);
  const text = render();
  const checkAt = args.indexOf("--check");
  const outAt = args.indexOf("--out");
  if (checkAt >= 0) {
    const current = readFileSync(args[checkAt + 1]!, "utf8");
    if (current !== text) {
      console.error("rg.conf differs from the generated gateway");
      process.exit(1);
    }
  } else if (outAt >= 0) writeFileSync(args[outAt + 1]!, text);
  else process.stdout.write(text);
}
