import { resolve } from "node:path";
import { checkBunRuntime } from "../validation/bun-runtime";

export interface BrandTheme {
  id: string;
  seed: string;
  dark: boolean;
  selectors: string[];
}

export interface BrandConfig {
  schemaVersion: 1;
  generator: "aphrody-m3-tokens";
  variant: string;
  contrast: number;
  themes: BrandTheme[];
}

export function parseBrandConfig(value: unknown): BrandConfig {
  if (typeof value !== "object" || value === null) throw new Error("Invalid RG M3 config");
  const config = value as BrandConfig;
  if (
    config.schemaVersion !== 1 ||
    config.generator !== "aphrody-m3-tokens" ||
    config.variant !== "tonal-spot" ||
    !Number.isFinite(config.contrast) ||
    config.contrast < -1 ||
    config.contrast > 1 ||
    !Array.isArray(config.themes) ||
    !config.themes.length
  )
    throw new Error("Invalid RG M3 generator contract");
  const ids = new Set<string>();
  const selectors = new Set<string>();
  for (const theme of config.themes) {
    if (
      typeof theme !== "object" ||
      theme === null ||
      typeof theme.id !== "string" ||
      typeof theme.seed !== "string" ||
      !/^[a-z][a-z0-9-]+$/.test(theme.id) ||
      !/^#[a-f\d]{6}$/i.test(theme.seed) ||
      typeof theme.dark !== "boolean" ||
      !Array.isArray(theme.selectors) ||
      !theme.selectors.length ||
      ids.has(theme.id)
    )
      throw new Error("Invalid RG M3 theme");
    ids.add(theme.id);
    for (const selector of theme.selectors) {
      if (typeof selector !== "string" || !/^(?::root)?\.[a-z][a-z0-9-]+$/.test(selector) || selectors.has(selector))
        throw new Error(`Invalid or repeated RG M3 selector: ${selector}`);
      selectors.add(selector);
    }
  }
  return config;
}

export function scopeNativeSheet(css: string, theme: BrandTheme): string {
  if (!css.includes("--md-sys-color-primary:") || !css.includes("--primary: var(--md-sys-color-primary);"))
    throw new Error("Native M3 sheet is missing its color/semantic alias contract");
  const roots = css.match(/:root\s*\{/g);
  if (roots?.length !== 2) throw new Error("Expected native scheme and semantic alias root blocks");
  return css.replaceAll(/:root\s*\{/g, `${theme.selectors.join(",\n")} {`);
}

export async function generateBrandCss(config: BrandConfig, generator: string): Promise<string> {
  const parts = [
    "/* SPDX-License-Identifier: Apache-2.0 */",
    "/* Generated by scripts/iecode/tools/rg-m3.ts from the native Aphrody M3 owner. */",
  ];
  for (const theme of config.themes) {
    const command = [
      generator,
      "--sheet",
      "scheme",
      "--seed",
      theme.seed,
      "--variant",
      config.variant,
      "--contrast",
      String(config.contrast),
      "--aliases",
    ];
    if (theme.dark) command.push("--dark");
    const process = Bun.spawn(command, { stdout: "pipe", stderr: "pipe" });
    const [stdout, stderr, exitCode] = await Promise.all([
      new Response(process.stdout).text(),
      new Response(process.stderr).text(),
      process.exited,
    ]);
    if (exitCode !== 0) throw new Error(`Native M3 generator failed for ${theme.id} (${exitCode}): ${stderr}`);
    parts.push(`/* ${theme.id}: ${theme.seed}, ${theme.dark ? "dark" : "light"}. */`, scopeNativeSheet(stdout, theme));
  }
  return `${parts.join("\n\n")}\n`;
}

if (import.meta.main) {
  const root = resolve(import.meta.dir, "../../..");
  await checkBunRuntime(root);
  const args = process.argv.slice(2);
  if (
    args[0] !== "--generator" ||
    args[2] !== "--output" ||
    !args[1] ||
    !args[3] ||
    args.length > 5 ||
    (args[4] !== undefined && args[4] !== "--check")
  )
    throw new Error(
      "Usage: bun scripts/iecode/tools/rg-m3.ts --generator <qualified-native-sheets> --output <canonical-rg-ui-brands.css> [--check]",
    );
  const config = parseBrandConfig(await Bun.file(resolve(root, "packages/rg-config/rg-m3.json")).json());
  const css = await generateBrandCss(config, resolve(args[1]!));
  const output = resolve(args[3]!);
  if (args[4] === "--check") {
    if (!(await Bun.file(output).exists()) || (await Bun.file(output).text()) !== css)
      throw new Error("RG M3 tokens are stale; regenerate with the qualified native sheets executable");
  } else {
    await Bun.write(output, css);
  }
  console.log(
    `RG M3: ${config.themes.length} native brand schemes ${args[4] === "--check" ? "verified" : "generated"}`,
  );
}
